#pragma once

// One source for the runtime, help, CMake and Windows resource versions.
// Keep these integer definitions simple: CMake reads them before project().
#define NAMEHOOK_VERSION_MAJOR 1
#define NAMEHOOK_VERSION_MINOR 43
#define NAMEHOOK_VERSION_PATCH 0
#define NAMEHOOK_STRINGIFY_INNER(value) #value
#define NAMEHOOK_STRINGIFY(value) NAMEHOOK_STRINGIFY_INNER(value)
#define NAMEHOOK_VERSION_TEXT NAMEHOOK_STRINGIFY(NAMEHOOK_VERSION_MAJOR) "." NAMEHOOK_STRINGIFY(NAMEHOOK_VERSION_MINOR)
#define NAMEHOOK_VERSION_FULL_TEXT NAMEHOOK_VERSION_TEXT "." NAMEHOOK_STRINGIFY(NAMEHOOK_VERSION_PATCH) ".0"
#define NAMEHOOK_VERSION (NAMEHOOK_VERSION_MAJOR + NAMEHOOK_VERSION_MINOR / 100.0)
