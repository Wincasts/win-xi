#!/usr/bin/env python3
"""Build the zone addon's region of each zone (addons/zone/data/regionZones.lua) from the server.

The server says which region a zone is in (src/map/utils/zoneutils.cpp, GetCurrentRegion: a case for
each zone, by the ZoneId enum's names, data/enums/zone.yaml's), in its own numbering (zone.h's
REGION_TYPE). zone shows a region by the client's name for it and its nation's flag, in the client's
numbering (addons/zone/data/regions.lua): each server region is taken to the client's of the same name,
and those named otherwise are in CLIENT_NAMED below. A zone the server puts in no region (a ship, Escha,
Dynamis - Divergence: nowhere conquest reaches) keeps the region the client's own grouping gives it,
Boussole's table (references/boussole/data/regionZones.lua, from Windower's resources), for its name.

Reads the live branch of phoenixffxi/Phoenix through tools/phoenix; stops where a C++ module or core
patch names the function, or the switch is not as it was.
"""
import argparse
import re
import sys
from pathlib import Path

from phoenix import modules, source

ROOT = Path(__file__).resolve().parents[1]
CLIENT_GROUPING = ROOT / 'references/boussole/data/regionZones.lua'
REGIONS = ROOT / 'addons/zone/data/regions.lua'
OUTPUT = ROOT / 'addons/zone/data/regionZones.lua'

# server regions whose client name is not theirs: REGION_TYPE -> the client's region number
CLIENT_NAMED = {
    'SANDORIA': 0, 'BASTOK': 1, 'WINDURST': 2, 'JEUNO': 3, 'QUFIMISLAND': 14, 'TAVNAZIAN_MARQ': 23,
    'TAVNAZIA': 24, 'MAMOOL_JA_SAVAGE': 30, 'HALVUNG': 31, 'ARRAPAGO': 32, 'ALZADAAL': 33,
    'SARUTA_FRONT': 38, 'ARAGONEAU_FRONT': 39, 'ADOULIN_ISLANDS': 50, 'EAST_ULBUKA': 51,
}


def squash(text):
    return re.sub(r'[^a-z0-9]', '', text.lower())


def build(server, output=OUTPUT):
    server = Path(server)
    found = modules.cpp_modules_mentioning(server, 'GetCurrentRegion', 'REGION_TYPE')
    if found:
        sys.exit(f'{", ".join(found)} name GetCurrentRegion or REGION_TYPE: read what they change first')
    header = (server / 'src/map/zone.h').read_text()
    enum = header[header.index('enum class REGION_TYPE'):]
    enum = enum[:enum.index('};')]
    server_regions = {name: int(value) for name, value in re.findall(r'^\s+(\w+)\s*=\s*(\d+),', enum, re.M)}
    zone_ids = {squash(name): number for name, number in modules.load_yaml(server, 'enums/zone')['values'].items()}

    code = modules.blank_cpp_comments((server / 'src/map/utils/zoneutils.cpp').read_text())
    start = code.index('auto GetCurrentRegion(const xi::ZoneId zoneId) -> REGION_TYPE')
    body = code[start:code.index('return REGION_TYPE::UNKNOWN;', start)]
    region_of, cases = {}, []
    for token in re.finditer(r'case xi::ZoneId::(\w+):|return REGION_TYPE::(\w+);', body):
        if token.group(1):
            cases.append(token.group(1))
        else:
            for name in cases:
                if squash(name) not in zone_ids:
                    sys.exit(f'zoneutils.cpp: ZoneId::{name} is not in data/enums/zone.yaml')
                region_of[zone_ids[squash(name)]] = token.group(2)
            cases = []
    if len(region_of) < 200:
        sys.exit(f'zoneutils.cpp: GetCurrentRegion gave only {len(region_of)} zones: read it again')

    client = {}
    for number, english, english2 in re.findall(r"\{ id = (\d+), en = (?:\"([^\"]+)\"|'([^']+)')", REGIONS.read_text(encoding='utf-8')):
        client[squash(english or english2)] = int(number)
    # the client's grouping, for the zones the server places nowhere
    grouping = {}
    for number, zones in re.findall(r'\[(\d+)\]\s*=\s*\{([^}]*)\}', CLIENT_GROUPING.read_text(encoding='utf-8')):
        for zone in re.findall(r'\d+', zones):
            grouping[int(zone)] = int(number)
    zones_by_region, kept = {}, 0
    for zone, number in sorted(grouping.items()):
        if zone not in region_of:
            zones_by_region.setdefault(number, []).append(zone)
            kept += 1
    for zone, region in sorted(region_of.items()):
        number = CLIENT_NAMED.get(region, client.get(squash(region)))
        if number is None:
            sys.exit(f'REGION_TYPE::{region} has no client region: add it to CLIENT_NAMED')
        zones_by_region.setdefault(number, []).append(zone)
    for zones in zones_by_region.values():
        zones.sort()

    found = source.read(server)
    lines = ['-- Generated by tools/build_zone_regions.py; do not edit.',
             f"-- Each region's zones, as the server places them ({found.repository} {found.branch} {found.commit[:9]}:",
             "-- zoneutils.cpp's GetCurrentRegion), by the client's region number (regions.lua); a zone the server",
             f"-- places nowhere ({kept} of them) as the client groups it (Boussole's regionZones.lua).",
             '', 'local regionZones = {}', '', 'regionZones.map = {']
    for number in sorted(zones_by_region):
        lines.append(f'    [{number}] = {{ {", ".join(map(str, zones_by_region[number]))} }},')
    lines += ['}', '', 'return regionZones', '']
    output.write_text('\n'.join(lines), encoding='utf-8')
    return len(region_of), len(zones_by_region)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    source.add_arguments(parser)
    found = source.from_arguments(parser.parse_args())
    print(f'Server: {found.describe()}')
    zones, regions = build(found.path)
    print(f'Wrote {OUTPUT}: {zones} zones in {regions} regions')
