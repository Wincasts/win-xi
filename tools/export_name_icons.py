#!/usr/bin/env python3
"""Export name's bundled player atlas/mapping from a local FFXI menu DAT.

Usage: python tools/export_name_icons.py /path/to/ROM/119/51.DAT
Requires Pillow. The addon uses only the exported files, not the DAT at runtime.
"""
import argparse
import io
import struct
from pathlib import Path
from PIL import Image


def export(source, destination):
    data = Path(source).read_bytes()
    picture = shapes = None
    offset = 0
    while offset + 16 <= len(data):
        meta = struct.unpack_from('<I', data, offset + 4)[0]
        kind, size = meta & 127, ((meta >> 7) & 0x7ffff) * 16
        if size < 16 or offset + size > len(data):
            raise ValueError('Invalid DAT chunk')
        chunk = data[offset:offset + size]
        if kind == 0x20 and chunk[17:33].lower() == b'menu    ustatshd':
            picture = chunk
        if kind == 0x31 and chunk[16:32] == b'font    fontshp ':
            shapes = chunk
        offset += size
    if picture is None or shapes is None:
        raise ValueError('High-resolution player atlas/fontshp not found')
    width, height = struct.unpack_from('<II', picture, 37)
    if (width, height) != (256, 256) or picture[73:77] != b'3TXD':
        raise ValueError('Expected a 256x256 DXT3 atlas')
    pixels = picture[85:85 + width * height]
    if len(pixels) != width * height:
        raise ValueError('Truncated DXT3 atlas')
    header = [0] * 32
    header[:6] = [0x20534444, 124, 0x81007, height, width, len(pixels)]
    header[19:22] = [32, 4, 0x33545844]
    header[27] = 0x1000
    image = Image.open(io.BytesIO(struct.pack('<32I', *header) + pixels)).convert('RGBA')
    # FFXI renders these half-opacity pixels at twice their alpha strength.
    image.putalpha(image.getchannel('A').point(lambda alpha: min(255, alpha * 2)))

    # fontshp: texture count + names, first byte/count, reserved byte, then
    # one piece-count per character. Each piece is 61 bytes: geometry, UV rectangle,
    # skip flag, colours/render flags and its 16-byte texture name.
    table = 32 + shapes[32] * 16
    first, count = shapes[table:table + 2]
    cursor = table + 3
    mapping = {}
    for byte in range(first, first + count):
        pieces = shapes[cursor]
        cursor += 1
        for _ in range(pieces):
            piece = shapes[cursor:cursor + 61]
            if len(piece) != 61:
                raise ValueError('Truncated font shape')
            w, h, x, y = struct.unpack_from('<4H', piece, 16)
            if byte >= 0x8e and piece[24] == 0 and byte not in mapping:
                if piece[45:61].lower() != b'menu    ustatshd':
                    raise ValueError('Unexpected icon texture')
                if not (w > 0 and h > 0 and x + w <= width and y + h <= height):
                    raise ValueError('Invalid icon UV rectangle')
                mapping[byte] = (x, y, x + w, y + h)
            cursor += 61
    if mapping.get(0x92) != (0, 64, 32, 96) or mapping.get(0xad) != (192, 64, 224, 96):
        raise ValueError('Unexpected pearl/mastery-star mapping')
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    image.save(destination / 'player-icons.png')
    lines = ['-- Generated by tools/export_name_icons.py; pixel rectangles in player-icons.png.', 'return {']
    lines += [f'    [0x{byte:02X}] = {{ {", ".join(map(str, rect))} }},' for byte, rect in mapping.items()]
    lines += ['};', '']
    (destination / 'player-icons.lua').write_text('\n'.join(lines))
    print(f'Exported {len(mapping)} icon mappings and 256x256 RGBA atlas to {destination}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source')
    parser.add_argument('--output', default='addons/name/assets')
    args = parser.parse_args()
    export(args.source, args.output)
