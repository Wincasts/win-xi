#!/usr/bin/env python3
"""Extract the installed FFXI client's auto-translate dictionary (no server fetch).

python3 tools/build_client_data.py --client '/path/to/FINAL FANTASY XI'
The known Japanese/English dictionary paths are ROM/168/24.DAT and 25.DAT.
Use repeatable --dat LANGUAGE=PATH for other dictionary files. Byte language IDs
are read from the files, never inferred from Ashita's language-array indices.
"""
import argparse
import hashlib
import json
import os
import shutil
import struct
import tempfile
from collections import defaultdict
from pathlib import Path

from build_item_data import lua

HEADER = struct.Struct('<I32s32sII')
PAGE_SIZE = 128


def parse_dictionary(data):
    """Strict reader for category_t/entry_t dictionaries; Japanese has a reading string."""
    offset, categories, entries = 0, {}, {}
    language = None
    def take(length):
        nonlocal offset
        if offset + length > len(data):
            raise ValueError(f'Truncated dictionary at {offset}, need {length} bytes')
        value = data[offset:offset + length]
        offset += length
        return value
    def text(value):
        return value.split(b'\0', 1)[0].decode('cp932', errors='strict')
    def sized():
        size = take(1)[0]
        if size == 0:
            raise ValueError('Empty dictionary string field')
        return text(take(size))
    while offset < len(data):
        ident, display, name, count, size = HEADER.unpack(take(HEADER.size))
        kind, lang, category, entry = ident.to_bytes(4, 'little')
        if kind != 2 or not lang or not category or entry != 0:
            raise ValueError(f'Invalid category header at {offset - HEADER.size}')
        if language is not None and language != lang:
            raise ValueError('Mixed language bytes in dictionary')
        language = lang
        if category in categories:
            raise ValueError('Duplicate category ID')
        categories[category] = {'Id': category, 'Name': text(name), 'DisplayName': text(display), 'Count': count}
        start = offset
        for _ in range(count):
            raw_id = int.from_bytes(take(4), 'little')
            ekind, elang, ecategory, number = raw_id.to_bytes(4, 'little')
            if (ekind, elang, ecategory) != (kind, lang, category) or number == 0:
                raise ValueError('Entry does not belong to its category')
            canonical = category * 256 + number
            if canonical in entries:
                raise ValueError('Duplicate phrase ID')
            record = {'Id': canonical, 'Category': category, 'Entry': number, 'RawId': raw_id, 'Text': sized()}
            if lang == 1:
                record['Reading'] = sized()
            entries[canonical] = record
        if offset - start != size:
            raise ValueError(f'Category {category} data size mismatch: expected {size}, read {offset - start}')
    if not categories:
        raise ValueError('Empty auto-translate dictionary')
    return language, categories, entries


def write_data(path, value):
    path.write_text('-- Generated by tools/build_client_data.py; client text is not server behavior.\nreturn ' + lua(value) + ';\n', encoding='utf-8')


def build(inputs, output, client_version=''):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    records, sources, languages, categories = {}, {}, {}, {}
    for locale, path in sorted(inputs.items()):
        if not locale or not locale.isascii() or not locale.replace('_', '').isalnum():
            raise ValueError('Locale must be an ASCII identifier')
        data = Path(path).read_bytes()
        language, cats, entries = parse_dictionary(data)
        languages[locale] = {'Byte': language, 'Count': len(entries)}
        sources[locale] = {'File': Path(path).name, 'SHA256': hashlib.sha256(data).hexdigest(), 'Size': len(data)}
        for ident, cat in cats.items():
            categories.setdefault(ident, {'Id': ident, 'Names': {}, 'DisplayNames': {}})
            categories[ident]['Names'][locale] = cat['Name']
            categories[ident]['DisplayNames'][locale] = cat['DisplayName']
        for ident, entry in entries.items():
            record = records.setdefault(ident, {'Id': ident, 'Category': entry['Category'], 'Entry': entry['Entry'], 'Text': {}, 'RawIds': {}, 'Readings': {}})
            record['Text'][locale] = entry['Text']
            record['RawIds'][locale] = entry['RawId']
            if 'Reading' in entry:
                record['Readings'][locale] = entry['Reading']
    pages = defaultdict(dict)
    for ident, record in sorted(records.items()):
        pages[ident // PAGE_SIZE][ident] = record
    for page, rows in pages.items():
        write_data(output / f'{page}.lua', rows)
    metadata = {'Schema': 1, 'Count': len(records), 'Ids': sorted(records), 'Pages': sorted(pages), 'PageSize': PAGE_SIZE,
                'Languages': languages, 'Categories': categories, 'Source': {'Type': 'installed-client', 'Version': client_version, 'Files': sources},
                'Limitations': ['Static dictionary phrases only. Item/key-item tokens use separate ID namespaces.',
                                'Client text/IDs may change with a client patch; rebuild from the matching installation.',
                                'No Phoenix gameplay availability is implied.']}
    write_data(output / 'index.lua', metadata)
    (output / 'catalog.json').write_text(json.dumps({'Metadata': metadata, 'Entries': list(records.values())}, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    (output / 'NOTICE.txt').write_text('Auto-translate text extracted from an installed Final Fantasy XI client.\nFinal Fantasy XI and its text belong to Square Enix; not relicensed under winxi\'s MIT license.\nindex.lua records dictionary file hashes; Version is optional user-supplied metadata.\n', encoding='utf-8')
    print(f'Auto-translate: {len(records)} phrases, {len(categories)} categories, languages: ' + ', '.join(languages))
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--client', type=Path, default=Path(os.environ.get('FFXI_DIR') or Path.home() / 'Games/PhoenixXI/SquareEnix/FINAL FANTASY XI'))
    parser.add_argument('--dat', action='append', default=[], metavar='LANGUAGE=PATH', help='Explicit dictionary inputs; replaces the default en/ja pair.')
    parser.add_argument('--client-version', default='', help='Optional user-supplied client version label (file hashes are always recorded).')
    parser.add_argument('--out', type=Path, default=Path(__file__).resolve().parents[1] / 'addons/libs/winxi/data/autotranslate')
    args = parser.parse_args()
    inputs = {'ja': args.client / 'ROM/168/24.DAT', 'en': args.client / 'ROM/168/25.DAT'}
    if args.dat:
        inputs = {}
        for option in args.dat:
            if '=' not in option:
                parser.error('--dat requires LANGUAGE=PATH')
            locale, path = option.split('=', 1)
            if locale in inputs:
                parser.error('Duplicate --dat language: ' + locale)
            inputs[locale] = Path(path)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=args.out.parent) as scratch:
        made = Path(scratch) / 'autotranslate'
        build(inputs, made, args.client_version)
        if args.out.exists():
            shutil.rmtree(args.out)
        shutil.move(str(made), str(args.out))


if __name__ == '__main__':
    main()
