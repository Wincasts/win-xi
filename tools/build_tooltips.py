#!/usr/bin/env python3
"""Build editable tooltip catalogues into Lua. No third-party dependencies."""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ID = re.compile(r"[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+")
LONG = re.compile(r'\[(=*)\[')
WORD = re.compile(r'[A-Za-z_][A-Za-z_0-9]*')


@dataclass(frozen=True)
class Entry:
    id: str
    label: str
    location: str
    text: str


def parse_catalogue(text: str, namespace: str) -> dict[str, Entry]:
    """## ID, Label/Location metadata, blank line, then plain tooltip text."""
    sections = re.split(r"^## (.+)\n", text.replace('\r\n', '\n'), flags=re.M)
    entries = {}
    for index in range(1, len(sections), 2):
        key, content = sections[index], sections[index + 1]
        if not ID.fullmatch(key) or key.split('.')[0] != namespace:
            raise ValueError(f"invalid ID/namespace: {key!r}")
        if key in entries:
            raise ValueError(f"duplicate ID: {key}")
        metadata, separator, body = content.lstrip('\n').partition('\n\n')
        lines = metadata.splitlines()
        if (not separator or len(lines) != 2 or not lines[0].startswith('Label: ')
                or not lines[1].startswith('Location: ')):
            raise ValueError(f"{key}: expected Label: and Location:, then a blank line")
        label, location = lines[0][7:].strip(), lines[1][10:].strip()
        body = body.strip('\n')
        if not label or not location or not body.strip():
            raise ValueError(f"{key}: label, location and tooltip text must not be empty")
        if any(ord(c) < 32 and c not in '\n\t' for c in body):
            raise ValueError(f"{key}: unsupported control character")
        entries[key] = Entry(key, label, location, body)
    if not entries:
        raise ValueError(f"{namespace}: no tooltip entries found")
    return entries


def lua_quote(text: str) -> str:
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t') + '"'


def render(entries: dict[str, Entry], source: str) -> str:
    lines = [f'-- Generated by tools/build_tooltips.py from {source}.',
             '-- Edit the Markdown catalogue, not this file.', 'return {']
    for key, entry in sorted(entries.items()):
        lines.append(f'    [{lua_quote(key)}] = {lua_quote(entry.text)},')
    return '\n'.join(lines + ['};', ''])


def lua_tokens(source: str):
    """Small lexer for reference validation: skip comments, keep quoted IDs.

    Not a Lua parser. Long strings/comments are consumed as a unit so example
    code in comments or tooltip text cannot count as a real reference.
    """
    at = 0
    while at < len(source):
        if source[at].isspace():
            at += 1
            continue
        comment = source.startswith('--', at)
        start = at + 2 if comment else at
        long = LONG.match(source, start)
        if long:
            close = ']' + long[1] + ']'
            end = source.find(close, start + len(long[0]))
            if end < 0:
                raise ValueError('unterminated Lua long string/comment')
            if not comment:
                yield ('string', source[start + len(long[0]):end])
            at = end + len(close)
        elif comment:
            end = source.find('\n', at)
            at = len(source) if end < 0 else end + 1
        elif source[at] in "\"'":
            quote, end = source[at], at + 1
            value = ''
            while end < len(source) and source[end] != quote:
                if source[end] == '\\':
                    end += 1
                    if end >= len(source):
                        raise ValueError('unterminated Lua string')
                    value += {'n': '\n', 'r': '\r', 't': '\t'}.get(source[end], source[end])
                else:
                    value += source[end]
                end += 1
            if end >= len(source):
                raise ValueError('unterminated Lua string')
            yield ('string', value)
            at = end + 1
        else:
            word = WORD.match(source, at)
            token = word[0] if word else source[at]
            yield ('code', token)
            at += len(token)


def references(source: str) -> set[str]:
    if not re.search(r'\btips\s*\.\s*Get\b', source):
        return set()
    tokens = list(lua_tokens(source))
    found = set()
    call = [('code', 'tips'), ('code', '.'), ('code', 'Get'), ('code', '(')]
    for at in range(len(tokens) - 4):
        if tokens[at:at + 4] == call:
            if at > 0 and tokens[at - 1] == ('code', 'function'):
                continue
            kind, key = tokens[at + 4]
            if kind != 'string' or not ID.fullmatch(key):
                raise ValueError('tips.Get requires a literal, namespaced tooltip ID')
            # Do not allow concatenated/dynamic IDs to masquerade as literal references.
            if at + 5 >= len(tokens) or tokens[at + 5] not in [('code', ')'), ('code', ',')]:
                raise ValueError(f'tips.Get: dynamic ID after {key!r}')
            found.add(key)
    return found


def build(root: Path, check: bool = False) -> int:
    catalogues = sorted((root / 'tooltips').glob('*.md'))
    catalogues = [p for p in catalogues if p.name != 'README.md']
    all_entries = {}
    outputs = []
    for path in catalogues:
        if not re.fullmatch(r'[a-z][a-z0-9_]*', path.stem):
            raise ValueError(f'invalid catalogue filename: {path.name}')
        entries = parse_catalogue(path.read_text(encoding='utf-8'), path.stem)
        all_entries.update(entries)
        target = root / 'addons/libs/winxi/data/tooltips' / (path.stem + '.lua')
        outputs.append((target, render(entries, path.relative_to(root).as_posix())))
    if not outputs:
        raise ValueError('no tooltip catalogues found')
    used = set()
    for path in sorted((root / 'addons').rglob('*.lua')):
        if 'data/tooltips' in path.as_posix():
            continue
        try:
            used.update(references(path.read_text(encoding='utf-8')))
        except ValueError as exc:
            raise ValueError(f'{path.relative_to(root)}: {exc}') from exc
    missing = used - all_entries.keys()
    if missing:
        raise ValueError('missing tooltip IDs: ' + ', '.join(sorted(missing)))
    for key in sorted(all_entries.keys() - used):
        print(f'warning: unused tooltip: {key}', file=sys.stderr)
    stale = False
    # Validate everything before writing any generated files.
    for target, content in outputs:
        previous = target.read_text(encoding='utf-8') if target.exists() else None
        if previous == content:
            continue
        if check:
            print(f'out of date: {target.relative_to(root)}', file=sys.stderr)
            stale = True
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding='utf-8')
            print(f'built {target.relative_to(root)}')
    print(f'{len(all_entries)} tooltips, {len(outputs)} catalogue(s) validated')
    return int(stale)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate and fail if generated Lua needs rebuilding; write nothing')
    args = parser.parse_args()
    try:
        return build(ROOT, args.check)
    except (ValueError, OSError, UnicodeError) as exc:
        print(f'tooltips: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
