"""tools/build_zone_entrances.py against a small made-up server."""
import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_zone_entrances import build  # noqa: E402

SETTINGS = ("INSERT INTO `zone_settings` VALUES (100,'0',0,'West_Ronfaure');\n"
            "INSERT INTO `zone_settings` VALUES (167,'0',0,'Bostaunieux_Oubliette');\n"
            "INSERT INTO `zone_settings` VALUES (230,'0',0,'Southern_San_dOria');\n"
            "INSERT INTO `zone_settings` VALUES (139,'0',0,'Horlais_Peak');\n")
ZONES = {
    'west_ronfaure': """type: [outdoors]
zonelines:
  a1:
    from: [-716.0, -42.0, 18.0]
    to: bostaunieux_oubliette
  a2:
    from: [-700.0, -40.0, 30.0]
    to: bostaunieux_oubliette
  a3:
    from: [-700.0, -80.0, 30.0]
    to: bostaunieux_oubliette
  b1:
    from: [100.0, 0.0, 100.0]
    to: southern_san_doria
  c1:
    from: [0.0, 0.0, 0.0]
    to: horlais_peak
""",
    'bostaunieux_oubliette': """type: [dungeon]
zonelines:
  d1:
    from: [1.0, 2.0, 3.0]
    to: west_ronfaure
""",
    'southern_san_doria': 'type: [city]\nzonelines: {}\n',
    'horlais_peak': 'zonelines: {}\n',
}


class EntranceTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        root = Path(self.folder.name)
        (root / 'sql').mkdir()
        (root / 'sql/zone_settings.sql').write_text(SETTINGS)
        for name, text in ZONES.items():
            (root / 'data/zones' / name).mkdir(parents=True)
            (root / 'data/zones' / name / 'zone.yaml').write_text(text)
        self.review = root / 'review.json'
        self.review.write_text(json.dumps({'100:a1': {'label': 'A', 'place': "Jack's Door"}}))
        self.output = root / 'entrances.lua'
        self.server = root

    def tearDown(self):
        self.folder.cleanup()

    def run_build(self):
        result = build(self.server, self.review, {167: 'Bostaunieux Oubliette', 100: 'West Ronfaure'}, self.output)
        return result, self.output.read_text()

    def test_only_lines_into_dungeons(self):
        (total, _, zones, _), text = self.run_build()
        self.assertEqual(zones, 1)
        self.assertNotIn('Southern', text)
        self.assertNotIn('Horlais', text)  # a battlefield has no type: not an entrance to announce
        self.assertNotIn('[167]', text)  # nor are a dungeon's ways out

    def test_near_lines_are_one_entrance_and_a_level_apart_are_not(self):
        (total, _, _, _), text = self.run_build()
        self.assertEqual(total, 2)
        self.assertIn("id = 'a1'", text)
        self.assertIn("id = 'a3'", text)
        self.assertNotIn("id = 'a2'", text)

    def test_review_number_and_place_and_ashita_axes(self):
        (_, numbered, _, unreviewed), text = self.run_build()
        self.assertEqual(numbered, 1)
        self.assertIn("label = 'A', place = 'Jack\\'s Door', x = -708.0, y = 24.0, z = -41.0", text)
        self.assertEqual(unreviewed, ['100:a3 West_Ronfaure -> Bostaunieux_Oubliette'])

    def test_the_output_loads_as_lua_text(self):
        _, text = self.run_build()
        self.assertTrue(text.startswith('-- Generated by tools/build_zone_entrances.py'))
        self.assertEqual(text.count('{'), text.count('}'))


if __name__ == '__main__':
    unittest.main()
