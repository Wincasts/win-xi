#!/usr/bin/env python3
"""Writes addons/atlas/data/maps.lua: every zone's maps, a floor to each, from addons/zone/data/all_maps.lua.

Each map is its floor's id, its place in the client's table of maps and its picture's file under the
game's folder. A floor with no place in the client's table is left out, as the client cannot say how
it lies over the zone; where a floor has several pictures, the first is kept, as mark keeps it.

    python3 tools/build_atlas_maps.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'addons/zone/data/all_maps.lua'
OUTPUT = ROOT / 'addons/atlas/data/maps.lua'

ROW = re.compile(r'zone_id = (\d+), name = "[^"]*", floor_id = (\d+), table_index = (\d+),.*?dat = "([^"]+)"')


def floors(text):
    """zone -> floor -> (index, dat), the first picture of each floor."""
    found = {}
    for zone, floor, index, dat in ROW.findall(text):
        found.setdefault(int(zone), {}).setdefault(int(floor), (int(index), dat))
    return found


def lua(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    zones = floors(SOURCE.read_text())
    lines = ['-- Generated by tools/build_atlas_maps.py from addons/zone/data/all_maps.lua',
             '-- Zone -> its maps: the floor\'s id, its place in the client\'s table of maps, and its picture\'s file',
             'return {']
    for zone, found in sorted(zones.items()):
        listed = ', '.join(f'{{ floor = {floor}, index = {index}, dat = {lua(dat)} }}'
                           for floor, (index, dat) in sorted(found.items()))
        lines.append(f'    [{zone}] = {{ {listed} }},')
    lines.append('};\n')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('\n'.join(lines))
    print(f'{OUTPUT.relative_to(ROOT)}: {len(zones)} zones, {sum(len(f) for f in zones.values())} maps')


if __name__ == '__main__':
    main()
