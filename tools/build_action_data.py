#!/usr/bin/env python3
"""Phoenix action/reference catalogs, used by build_winxi_data.py.

Binary job arrays are preserved losslessly (not parsed as 176-bit SQL integers).
Lua sources are evidence only; no server code is executed.
"""
import hashlib
import io
import json
import re
import shutil
import sqlite3
from collections import defaultdict
from pathlib import Path

from phoenix import modules, source
from build_item_data import enabled_files, replay, snapshot, lua

CONFIG = {
    'spells': ('spell_list', ('blue_spell_list', 'blue_spell_mods'), 'spells'),
    'abilities': ('abilities', ('abilities_charges',), 'abilities'),
    'weaponskills': ('weapon_skills', (), 'weaponskills'),
    'traits': ('traits', ('blue_traits',), None),
}
PAGE_SIZE = 128


def write_data(path, value):
    path.write_text('-- Generated by tools/build_action_data.py; do not edit.\nreturn ' + lua(value) + ';\n', encoding='utf-8')


def binary_sql(sql, table):
    if table not in ('spell_list', 'weapon_skills'):
        return sql
    # Full-width job literals are blobs, while scalar hex (e.g. an element mask) stays
    # numeric. INSERT's fourth argument is binary even for a one-byte 0x00 replacement.
    # Track the function arguments without touching quoted text or identifiers.
    depth, calls = 0, []
    def replace(match):
        nonlocal depth
        token = match[0]
        if token.startswith(("'", '`')):
            return token
        if token.lower().startswith('0x'):
            binary = len(token[2:]) > 16 or calls and calls[-1][1] == 3
            return "X'" + token[2:] + "'" if binary else token
        if re.match(r'INSERT', token, re.I):
            depth += 1
            calls.append([depth, 0])
            return 'BLOB_INSERT('
        if token == '(':
            depth += 1
        elif token == ')':
            if calls and calls[-1][0] == depth:
                calls.pop()
            depth -= 1
        elif token == ',' and calls and calls[-1][0] == depth:
            calls[-1][1] += 1
        return token
    return re.sub(r"'(?:''|[^'])*'|`[^`]*`|0[xX][0-9a-fA-F]+|\bINSERT\s*\(|[(),]", replace, sql, flags=re.I)


def blob_insert(value, position, length, replacement):
    # MySQL INSERT(str,pos,len,newstr), with one-based BYTE positions for BINARY.
    if position < 1 or position > len(value):
        return value
    return value[:position - 1] + replacement + value[position - 1 + length:]


def lua_without_comments(text):
    # Preserve quoted strings while discarding line/long comments. This is an indexer,
    # not a Lua evaluator; dynamic target construction remains explicitly unresolved.
    return re.sub(r"--\[(=*)\[[\s\S]*?\]\1\]|--[^\n]*|'(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"",
                  lambda m: ' ' if m[0].startswith('--') else m[0], text)


def clean(value):
    if isinstance(value, bytes):
        return value.hex().upper()
    if isinstance(value, list):
        return [clean(v) for v in value]
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items()}
    return value


def provenance(server):
    found = source.read(server)
    return {'Repository': found.repository, 'Branch': found.branch, 'Commit': found.commit, 'Committed': found.committed}


def enum(server, name):
    return modules.load_yaml(server, f'enums/{name}')['values']


def publish(server, output, kind, records, metadata, scripts=None):
    output.mkdir(parents=True, exist_ok=True)
    scripts = scripts or {}
    pages = defaultdict(dict)
    for ident, record in sorted(records.items()):
        pages[ident // PAGE_SIZE][ident] = record
    for page, rows in pages.items():
        write_data(output / f'{page}.lua', rows)
    script_index, script_pages = {}, defaultdict(dict)
    for n, (path, evidence) in enumerate(sorted(scripts.items())):
        script_index[path] = n // 32
        script_pages[n // 32][path] = evidence
    for page, values in script_pages.items():
        write_data(output / f'script_{page}.lua', values)
    metadata.update({'Schema': 1, 'Kind': kind, 'Count': len(records), 'Ids': sorted(records),
                     'Pages': sorted(pages), 'PageSize': PAGE_SIZE, 'Scripts': script_index, 'Source': provenance(server)})
    write_data(output / 'index.lua', metadata)
    (output / 'catalog.json').write_text(json.dumps({'Metadata': metadata, 'Entries': list(records.values())}, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    shutil.copyfile(server / 'LICENSE', output / 'LICENSE-Phoenix')
    (output / 'NOTICE.txt').write_text('Derived from Phoenix (https://github.com/phoenixffxi/Phoenix).\nServer script sources retain the upstream GPL v3 license; see LICENSE-Phoenix.\nNot relicensed under winxi\'s MIT license. Source revision and original paths are in index.lua.\n', encoding='utf-8')
    print(f'{kind}: {len(records)} definitions; {len(scripts)} source files')


def build_actions(server, output, settings, kind):
    server, output = Path(server), Path(output)
    table, extras, folder = CONFIG[kind]
    tables = (table,) + extras
    db = sqlite3.connect(':memory:')
    db.row_factory = sqlite3.Row
    db.create_function('BLOB_INSERT', 4, blob_insert)
    variables = {}
    for name in tables:
        replay(db, server / f'sql/{name}.sql', variables, tables=tables, transform=binary_sql)
    baseline = {name: snapshot(db, name) for name in tables}
    applied = []
    for path in enabled_files(server, '.sql'):
        touched = replay(db, path, variables, True, tables=tables, transform=binary_sql)
        if touched:
            applied.append(str(path.relative_to(server)))
    current = {name: snapshot(db, name) for name in tables}
    records = {}
    for ident, rows in sorted(current[table].items()):
        record = {'Id': ident, 'Name': rows[0]['name'].replace('_', ' ')}
        if kind == 'traits':
            record['Rows'] = rows  # trait IDs have many jobs, levels, ranks and modifiers
        else:
            row = rows[0]
            record['Data'] = clean(row)
            if 'jobs' in row:
                job_bytes = row['jobs']
                if not isinstance(job_bytes, bytes) or len(job_bytes) != 22:
                    raise ValueError(f'{kind} {ident}: expected exactly 22 job bytes')
                record['Jobs'] = {job: value for job, value in enumerate(job_bytes, 1) if value}
            else:
                record['Jobs'] = {row['job']: row['level']} if row['job'] > 0 else {}
        changed = [name for name in (table,) if baseline[name].get(ident) != rows]
        if kind == 'spells':
            for name, field in (('blue_spell_list', 'Blue'), ('blue_spell_mods', 'BlueMods')):
                if ident in current[name]:
                    record[field] = clean(current[name][ident])
                if baseline[name].get(ident) != current[name].get(ident):
                    changed.append(name)
        if kind == 'abilities':
            recast = rows[0]['recastId']
            if recast in current['abilities_charges']:
                record['Charges'] = current['abilities_charges'][recast]
            if baseline['abilities_charges'].get(recast) != current['abilities_charges'].get(recast):
                changed.append('abilities_charges')
        if kind == 'traits':
            blue = [dict(r) for r in db.execute('SELECT * FROM blue_traits WHERE traitid = ? ORDER BY trait_category,trait_points_needed,tier,modifier', (ident,))]
            if blue:
                record['Blue'] = blue
            old_blue = [r for rows_by_category in baseline['blue_traits'].values() for r in rows_by_category if r['traitid'] == ident]
            if sorted(old_blue, key=lambda r: tuple(r.values())) != sorted(blue, key=lambda r: tuple(r.values())):
                changed.append('blue_traits')
        if changed:
            record['Changed'] = changed
        records[ident] = record

    scripts, declarations = {}, []
    def evidence(path):
        key = str(path.relative_to(server))
        text = path.read_text(encoding='utf-8-sig')
        scripts[key] = {'Path': key, 'SHA256': hashlib.sha256(text.encode()).hexdigest(), 'Text': text}
        return key
    # Match actual paths, not only leaf names (spells have white/black/songs subfolders).
    by_target = {}
    if folder:
        root = server / 'scripts/actions' / folder
        by_name = defaultdict(list)
        for record in records.values():
            by_name[record['Data']['name']].append(record)
        for path in sorted(root.rglob('*.lua')):
            matching = by_name.get(path.stem, [])
            if matching:
                key = evidence(path)
                target = 'xi.actions.' + path.relative_to(server / 'scripts/actions').with_suffix('').as_posix().replace('/', '.')
                by_target[target] = matching
                for record in matching:
                    record.setdefault('Sources', []).append(key)
        # every module override on live of an action's script, or of the shared functions the actions
        # call (phoenix.modules: gates evaluated, overrides made in loops found), as evidence
        related = []
        shared = {'spells': 'xi.spells.', 'abilities': 'xi.job_utils.', 'weaponskills': 'xi.weaponskills.'}[kind]
        actions = 'xi.actions.' + folder + '.'

        def handle(override):
            if override.target == '?':
                # a target not written out: only one whose code is an action's would matter here
                return None if re.search(r'\b(onSpellCast|onUseAbility|onAbilityCheck|onUseWeaponSkill|onMagicCastingCheck)', override.body) else 'target not written out; not an action\'s code'
            key = evidence(server / 'modules' / override.path)
            if key not in related:
                related.append(key)
            status = 'on live' if override.applies else f'gate not understood, taken as on: {override.condition}'
            declarations.append({'Path': key, 'Target': override.target, 'Status': status})
            if not override.target.startswith(actions):
                return 'a shared function the actions call: listed'
            base = override.target.rpartition('.')[0]
            for record in by_target.get(base, []):
                record.setdefault('Overrides', []).append(declarations[-1])
            return f'replaces {override.target.rpartition(".")[2]} of {len(by_target.get(base, []))} action(s)'

        modules.guard(server, (actions, shared), handle, out=io.StringIO())
    else:
        related = []
    enums = {name: enum(server, name) for name in ('job', 'skill_type', 'element', 'mod')}
    sc_text = (server / 'scripts/enum/skillchain_type.lua').read_text()
    enums['skillchain'] = {name: int(value) for name, value in re.findall(r'^\s*(\w+)\s*=\s*(\d+)', sc_text, re.M)}
    metadata = {'Settings': list(settings), 'SQL': applied, 'Enums': enums, 'Declarations': declarations,
                'RelatedModules': related, 'ChangedCount': sum('Changed' in r for r in records.values()),
                'Limitations': [
                    'Presence and ForJob lists do not prove availability, unlocks, learned status or content access.',
                    'SQL is a clean import with enabled module SQL, not private live database edits.',
                    'Lua overrides are listed with their module gates evaluated for live (expansions from WotG on taken as off); what they do, and their super chains, are not.',
                    'Shared globals, C++ rules and dynamic overrides are not fully associated with individual actions.',
                    'Client descriptions are presentation only. Modifier values retain server units.',
                ]}
    publish(server, output, kind, records, metadata, scripts)
    db.close()


def build_reference(server, output, settings, kind):
    server, output = Path(server), Path(output)
    enum_name = {'jobs': 'job', 'skills': 'skill_type', 'elements': 'element'}[kind]
    values = enum(server, enum_name)
    records = {ident: {'Id': ident, 'Name': name.replace('_', ' '), 'Symbol': name.upper()} for name, ident in values.items()}
    metadata = {'Settings': list(settings), 'Overlays': [], 'Limitations': ['Reference definitions include later-era values; presence does not prove content availability.']}
    if kind == 'jobs':
        text = (server / 'scripts/enum/job_name.lua').read_text()
        for ident, abbr, name in re.findall(r"\[\s*(\d+)\]\s*=\s*\{\s*'([^']+)',\s*'([^']+)'", text):
            if int(ident) in records:
                records[int(ident)].update({'Abbreviation': abbr, 'Name': name})
    if kind == 'skills':
        # as live loads it: the modules' skills.yaml merged in (RFC 7396)
        skills = modules.load_yaml(server, 'skills')
        metadata['Overlays'] = [path.relative_to(server).as_posix() for path in modules.data_patches(server, 'skills')]
        jobs = enum(server, 'job')
        for name, ident in values.items():
            records[ident]['Ranks'] = {jobs[job]: rank for job, rank in skills['skills']['ranks'].get(name, {}).items()}
        metadata['Caps'] = skills['skills']['caps']
    publish(server, output, kind, records, metadata)


def build_statuses(server, output, settings):
    """Every status effect the server has (data/status_effects.yaml as the modules patch it): its
    number, the server's name for it, its flags (erasable, waltzable, dispelable, no_cancel, ...),
    element, how a stronger one overwrites it, and the message that says it wore off."""
    server, output = Path(server), Path(output)
    document = modules.load_yaml(server, 'status_effects')
    records = {}
    for key, entry in (document.get('status_effects') or {}).items():
        if not isinstance(entry, dict) or 'id' not in entry:
            continue
        ident = int(entry['id'])
        record = {'Id': ident, 'Name': str(entry.get('name') or key).replace('_', ' '), 'Symbol': key.upper(),
                  'Flags': sorted(entry.get('flags') or [])}
        for field, name in (('element', 'Element'), ('overwrite', 'Overwrite'), ('wear_off_message_id', 'WearOff')):
            if entry.get(field) is not None:
                record[name] = entry[field]
        records[ident] = record
    metadata = {'Settings': list(settings),
                'Patches': [path.relative_to(server).as_posix() for path in modules.data_patches(server, 'status_effects')],
                'Limitations': ['Flags are the server\'s; which statuses harm is not a flag of its own: '
                                'erasable and waltzable say what removes them.']}
    publish(server, output, 'statuses', records, metadata)


def builder(kind):
    def build(server, output, settings):
        if kind in CONFIG:
            build_actions(server, output, settings, kind)
        else:
            build_reference(server, output, settings, kind)
    return build
