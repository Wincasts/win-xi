#!/usr/bin/env python3
"""Build the casttimes set (addons/libs/winxi/data/<server>/casttimes; a set of build_winxi_data), Name's base monster ready times from Phoenix as live runs it (not runtime durations).

sql/mob_skills.sql, with the module SQL init.txt loads replayed over it (a move's ready time
changed, a move's row replaced), and the Lua module overrides of monsters' moves and zones put
through phoenix.modules.guard: a move's script cannot change its ready time, but a monster's
script can give one use of a move its own (useMobAbility's third argument), per monster, which a
table of moves cannot hold.

Use --server <checkout> to avoid fetching. Timings are estimates: packets do not carry the
authoritative remaining cast time.
"""
import argparse
import csv
import io
import re
import sqlite3
from pathlib import Path

from build_item_data import enabled_files, replay
from phoenix import modules, source

ROOT = Path(__file__).resolve().parents[1]
TABLES = ('mob_skills',)


def checked(pairs):
    """{move: seconds} from (move, milliseconds) pairs, those of 0 left out."""
    rows = {}
    for key, milliseconds in pairs:
        key, milliseconds = int(key), int(milliseconds)
        if not 0 < key < 65536 or not 0 <= milliseconds <= 120000:
            raise ValueError('out-of-bounds ready time')
        if milliseconds:
            rows[key] = milliseconds / 1000
    if not rows:
        raise ValueError('no monster ready times found')
    return rows


def parse(text):
    """The ready times of mob_skills.sql's rows as written, without modules."""
    pairs = []
    # a row commented out (-- INSERT ...) is one the server never loads
    for match in re.finditer(r"^[ \t]*INSERT INTO `mob_skills` VALUES \(([^\n]+)\);", text, re.M):
        fields = next(csv.reader(io.StringIO(match[1]), quotechar="'", escapechar='\\'))
        if len(fields) < 8:
            raise ValueError('short mob_skills row')
        pairs.append((fields[0], fields[7]))
    return checked(pairs)


def ready_times(server):
    """{move: seconds} as live has them: the base table and then the module SQL over it, and the
    module SQL files that changed it."""
    server = Path(server)
    db = sqlite3.connect(':memory:')
    variables = {}
    replay(db, server / 'sql/mob_skills.sql', variables, tables=TABLES)
    applied = []
    for path in enabled_files(server, '.sql'):
        if replay(db, path, variables, True, tables=TABLES):
            applied.append(path.relative_to(server).as_posix())
    rows = checked(db.execute('SELECT mob_skill_id, mob_prepare_time FROM mob_skills'))
    db.close()
    return rows, applied


def handle(override):
    """What a Lua override does to ready times: a monster's own for one use, or nothing."""
    body = override.body
    if re.search(r'ActivationTime|prepare_?time|PrepareTime', body, re.I):
        return None
    for m in re.finditer(r'\buseMobAbility\s*\(', body):
        if len(modules.arguments(body, m.end() - 1)) >= 3:
            return 'gives one monster\'s use of a move its own ready time: per monster, not kept'
    return 'leaves ready times'


def render(rows, describe='Phoenix'):
    return '\n'.join([
        f'-- Generated by tools/build_name_cast_times.py from {describe}:',
        '-- sql/mob_skills.sql and the module SQL live loads over it.',
        '-- Base ready times in seconds, keyed by protocol skill ID. Estimates only;',
        '-- a monster\'s own script may give one use its own, and that is not in start packets.',
        'return {',
        *[f'    [{key}] = {value:g},' for key, value in sorted(rows.items())],
        '};', '',
    ])


def build(server, output, settings=(), verbose=False):
    """The casttimes set: output/index.lua, for the server's checkout at server."""
    found = source.read(server)
    rows, applied = ready_times(found.path)
    done = modules.guard(found.path, ('xi.actions.mobskills.', 'xi.mobskills.', 'xi.zones.'), handle,
                         out=None if verbose else io.StringIO())
    own = [o for o, what in done if what.startswith('gives')]
    output.mkdir(parents=True, exist_ok=True)
    (output / 'index.lua').write_text(render(rows, found.describe()))
    print(f'{len(rows)} base ready times from {found.describe()} -> {output}')
    for path in applied:
        print(f'  module SQL {path}')
    print(f'  {len(done)} module overrides looked at; {len(own)} give a monster its own ready time:')
    for override in own:
        print(f'    {override.target} ({override.where()})')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source.add_arguments(parser)
    parser.add_argument('--out', type=Path, default=None, help='The set\'s folder; default data/<server>/casttimes.')
    parser.add_argument('--verbose', action='store_true', help='List every module override looked at.')
    args = parser.parse_args()
    found = source.from_arguments(args)
    build(found.path, args.out or ROOT / 'addons/libs/winxi/data' / source.KEY / 'casttimes', verbose=args.verbose)


if __name__ == '__main__':
    main()
