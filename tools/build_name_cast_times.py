#!/usr/bin/env python3
"""Build Name's base monster ready times from a Phoenix checkout (not runtime durations).

Use --server <checkout> to avoid fetching. Timings are estimates: scripts may override
mob_prepare_time, and packets do not carry authoritative remaining cast time.
"""
import argparse
import csv
import io
import re
from pathlib import Path
from phoenix import source

ROOT = Path(__file__).resolve().parents[1]


def parse(text):
    rows = {}
    for match in re.finditer(r"INSERT INTO `mob_skills` VALUES \(([^\n]+)\);", text):
        fields = next(csv.reader(io.StringIO(match[1]), quotechar="'", escapechar='\\'))
        if len(fields) < 8:
            raise ValueError('short mob_skills row')
        key, milliseconds = int(fields[0]), int(fields[7])
        if not 0 < key < 65536 or not 0 <= milliseconds <= 120000:
            raise ValueError('out-of-bounds ready time')
        if milliseconds:
            rows[key] = milliseconds / 1000
    if not rows:
        raise ValueError('no monster ready times found')
    return rows


def render(rows):
    return '\n'.join([
        '-- Generated by tools/build_name_cast_times.py from Phoenix sql/mob_skills.sql.',
        '-- Base ready times in seconds, keyed by protocol skill ID. Estimates only;',
        '-- script overrides/actor modifiers are not transmitted in start packets.',
        'return {',
        *[f'    [{key}] = {value:g},' for key, value in sorted(rows.items())],
        '};', '',
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source.add_arguments(parser)
    parser.add_argument('--out', type=Path, default=ROOT / 'addons/name/assets/mob_cast_times.lua')
    args = parser.parse_args()
    found = source.from_arguments(args)
    rows = parse((found.path / 'sql/mob_skills.sql').read_text())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows))
    print(f'{len(rows)} base ready times from {found.describe()} -> {args.out}')


if __name__ == '__main__':
    main()
