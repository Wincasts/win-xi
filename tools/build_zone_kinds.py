#!/usr/bin/env python3
"""Build vis's and zone's zone kinds from the Phoenix server's zone data.

Every zone the server has is one of three kinds for vis's presets and zone's Kind Frames: a city, outdoors, or a
dungeon. The server types each zone in data/zones/<name>/zone.yaml (city, outdoors, dungeon,
instanced, dynamis, or no type at all for a battlefield or a cloister); the ids are in
sql/zone_settings.sql. Instanced, dynamis and untyped zones are enclosed places, so they are
dungeons here. A zone the server has an id for but no data folder is left out: vis treats
it as of no known kind and draws it with the general values.

Writes addons/vis/zones.lua and addons/zone/data/zone_kinds.lua, the same table in each, for
each addon is deployed without the other. Reads the live branch of phoenixffxi/Phoenix, fetched from
GitHub (tools/phoenix), as live loads it: module SQL over zone_settings and each zone.yaml
patched by the modules (phoenix.modules.load_yaml).
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from phoenix import modules, source  # noqa: E402
from build_item_data import enabled_files, replay  # noqa: E402
import sqlite3  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
KINDS = {'city': 'city', 'outdoors': 'outdoors', 'dungeon': 'dungeon', 'instanced': 'dungeon', 'dynamis': 'dungeon', None: 'dungeon'}


def zone_ids(server):
    """zone id -> the server's folder name for it, from zone_settings.sql and the module SQL over it."""
    found = {}
    for zone, name in zone_rows(server, 'zoneid, name'):
        found[int(zone)] = name
    if not found:
        sys.exit('No zones found in sql/zone_settings.sql')
    return found


def zone_rows(server, columns):
    """The rows of zone_settings as live has them: the server's SQL and the module SQL over it."""
    db = sqlite3.connect(':memory:')
    variables = {}
    replay(db, server / 'sql/zone_settings.sql', variables, tables=('zone_settings',))
    for path in enabled_files(server, '.sql'):
        replay(db, path, variables, True, tables=('zone_settings',))
    rows = db.execute(f'SELECT {columns} FROM zone_settings').fetchall()
    db.close()
    return rows


def zone_type(server, name):
    """The server's type for the zone, None for none, or False when there is no zone file."""
    folder = re.sub(r'[^a-z0-9_]', '', name.lower().replace('-', '_'))  # Dynamis-Xarcabard_[S] -> dynamis_xarcabard_s
    document = modules.load_yaml(server, f'zones/{folder}/zone')
    if document is None:
        return False
    types = document.get('type') or []
    if not types:
        return None
    if types[0] not in KINDS:
        sys.exit(f'zones/{folder}/zone.yaml: unknown zone type {types[0]!r}')
    return types[0]


def build(server, outputs):
    ids = zone_ids(server)
    kinds, counts, skipped = {}, {}, []
    for zone, name in sorted(ids.items()):
        if zone == 0:  # the pre-release demonstration area, which vis takes as no zone at all
            continue
        found = zone_type(server, name)
        if found is False:
            skipped.append(f'{name} ({zone})')
            continue
        kinds[zone] = KINDS[found]
        counts[kinds[zone]] = counts.get(kinds[zone], 0) + 1
    lines = ['-- Generated by tools/build_zone_kinds.py; do not edit.',
             "-- Each zone's kind for vis's presets and zone's Kind Frames: 'city', 'outdoors' or 'dungeon' (the server's dungeon,",
             '-- instanced, dynamis and untyped zones). A zone not here is of no known kind.',
             'return {']
    for zone in sorted(kinds):
        lines.append(f"    [{zone}] = '{kinds[zone]}', -- {ids[zone]}")
    lines.append('}')
    for output in outputs:
        output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return counts, skipped


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    source.add_arguments(parser)
    parser.add_argument('--output', type=Path, action='append',
                        help='where to write it (more than once for more); vis\'s and zone\'s to start')
    args = parser.parse_args()
    found = source.from_arguments(args)
    print(f'Server: {found.describe()}')
    outputs = args.output or [ROOT / 'addons/vis/zones.lua', ROOT / 'addons/zone/data/zone_kinds.lua']
    counts, skipped = build(found.path, outputs)
    print(f'Wrote {", ".join(map(str, outputs))}: ' + ', '.join(f'{n} {k}' for k, n in sorted(counts.items())))
    if skipped:
        print(f'No zone file for {len(skipped)} zone(s), left out: ' + ', '.join(skipped))
