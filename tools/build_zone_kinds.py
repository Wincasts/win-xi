#!/usr/bin/env python3
"""Build drawscale's zone kinds from the Phoenix server's zone data.

Every zone the server has is one of three kinds for drawscale's presets: a city, outdoors, or a
dungeon. The server types each zone in data/zones/<name>/zone.yaml (city, outdoors, dungeon,
instanced, dynamis, or no type at all for a battlefield or a cloister); the ids are in
sql/zone_settings.sql. Instanced, dynamis and untyped zones are enclosed places, so they are
dungeons here. A zone the server has an id for but no data folder is left out: drawscale treats
it as of no known kind and draws it with the general values.

Writes addons/drawscale/zones.lua. Reads the live branch of phoenixffxi/Phoenix, fetched from
GitHub (tools/phoenix).
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from phoenix import source  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
KINDS = {'city': 'city', 'outdoors': 'outdoors', 'dungeon': 'dungeon', 'instanced': 'dungeon', 'dynamis': 'dungeon', None: 'dungeon'}


def zone_ids(server):
    """zone id -> the server's folder name for it, from zone_settings.sql."""
    text = (server / 'sql/zone_settings.sql').read_text(encoding='utf-8')
    found = {}
    for match in re.finditer(r"INSERT INTO `zone_settings` VALUES \((\d+),'[^']*',\d+,'([^']+)'\)", text):
        found[int(match.group(1))] = match.group(2)
    if not found:
        sys.exit('No zones found in sql/zone_settings.sql')
    return found


def zone_type(server, name):
    """The server's type for the zone, None for none, or False when there is no zone file."""
    folder = re.sub(r'[^a-z0-9_]', '', name.lower().replace('-', '_'))  # Dynamis-Xarcabard_[S] -> dynamis_xarcabard_s
    path = server / 'data/zones' / folder / 'zone.yaml'
    if not path.exists():
        return False
    match = re.search(r'^type:\s*\[([^\]]*)\]', path.read_text(encoding='utf-8'), re.M)
    if match is None:
        return None
    types = [t.strip() for t in match.group(1).split(',') if t.strip()]
    if not types:
        return None
    if types[0] not in KINDS:
        sys.exit(f'{path}: unknown zone type {types[0]!r}')
    return types[0]


def build(server, output):
    ids = zone_ids(server)
    kinds, counts, skipped = {}, {}, []
    for zone, name in sorted(ids.items()):
        if zone == 0:  # the pre-release demonstration area, which drawscale takes as no zone at all
            continue
        found = zone_type(server, name)
        if found is False:
            skipped.append(f'{name} ({zone})')
            continue
        kinds[zone] = KINDS[found]
        counts[kinds[zone]] = counts.get(kinds[zone], 0) + 1
    lines = ['-- Generated by tools/build_zone_kinds.py; do not edit.',
             "-- Each zone's kind for drawscale's presets: 'city', 'outdoors' or 'dungeon' (the server's dungeon,",
             '-- instanced, dynamis and untyped zones). A zone not here is of no known kind.',
             'return {']
    for zone in sorted(kinds):
        lines.append(f"    [{zone}] = '{kinds[zone]}', -- {ids[zone]}")
    lines.append('}')
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return counts, skipped


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    source.add_arguments(parser)
    parser.add_argument('--output', type=Path, default=ROOT / 'addons/drawscale/zones.lua')
    args = parser.parse_args()
    found = source.from_arguments(args)
    print(f'Server: {found.describe()}')
    counts, skipped = build(found.path, args.output)
    print(f'Wrote {args.output}: ' + ', '.join(f'{n} {k}' for k, n in sorted(counts.items())))
    if skipped:
        print(f'No zone file for {len(skipped)} zone(s), left out: ' + ', '.join(skipped))
