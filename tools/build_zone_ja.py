#!/usr/bin/env python3
"""Build the zone addon's Japanese zone names from Boussole's zone table.

Boussole's data/zones.lua is Windower's zone resources, which are read out of the game client's own
string tables, so each name is the one the Japanese client shows (King Ranperre's Tomb is
龍王ランペールの墓, not a translation of the English). The Kanji Watermark banner writes these.
Region names are already in addons/zone/data/regions.lua, from the same source.

Writes addons/zone/data/zone_names_ja.lua. Reads references/boussole/data/zones.lua, or the file
given.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROW = re.compile(r"\[(\d+)\] = \{ id = \d+, en = (\"[^\"]*\"|'[^']*'), ja = (\"[^\"]*\"|'[^']*')")


def names(text):
    """zone id -> (English, Japanese), leaving out the placeholders."""
    found = {}
    for match in ROW.finditer(text):
        zone, en, ja = int(match.group(1)), match.group(2)[1:-1], match.group(3)[1:-1]
        if ja and ja != 'unknown':
            found[zone] = (en.replace("\\'", "'"), ja)
    return found


def lua(found):
    lines = [
        '-- Generated by tools/build_zone_ja.py; do not edit.',
        "-- Each zone's name in the Japanese client, by zone ID, from Boussole's zone table (Windower's",
        "-- resources, read out of the client's string tables). Read by the Kanji Watermark banner.",
        'return {',
    ]
    for zone in sorted(found):
        en, ja = found[zone]
        lines.append(f"    [{zone}] = '{ja}', -- {en}")
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('zones', nargs='?', default=ROOT / 'references/boussole/data/zones.lua', type=Path)
    parser.add_argument('--out', default=ROOT / 'addons/zone/data/zone_names_ja.lua', type=Path)
    args = parser.parse_args()
    found = names(args.zones.read_text(encoding='utf-8'))
    if any("'" in ja or '\\' in ja for _, ja in found.values()):
        raise SystemExit('a Japanese name holds a quote or backslash; quote it properly first')
    args.out.write_text(lua(found), encoding='utf-8')
    print(f'{len(found)} zones written to {args.out}')


if __name__ == '__main__':
    main()
