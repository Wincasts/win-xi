package.path = 'addons/mark/?.lua;' .. package.path
local view = require('map_view')
local function near(a, b) return math.abs(a - b) < 1e-8 end
local s = view.New()
assert(s.zoom == 1 and s.x == 0 and s.y == 0)
view.Zoom(s, 2, 100, 200)
assert(s.zoom == 2 and s.x == -100 and s.y == -200)
local x, y = view.ToMap(s, 100, 200)
assert(near(x, 100) and near(y, 200), 'zoom preserves the point under the mouse')
local vx, vy = view.ToViewport(s, x, y)
assert(near(vx, 100) and near(vy, 200), 'transform round trip')
view.Pan(s, -20, 30)
assert(s.x == -120 and s.y == -170)
view.Pan(s, -10000, 10000)
assert(s.x == -512 and s.y == 0, 'pan clamps to map edges')
view.Zoom(s, 100, 256, 256)
assert(s.zoom == 6)
view.Zoom(s, .01, 256, 256)
assert(s.zoom == 1 and s.x == 0 and s.y == 0)
view.Pan(s, 50, -50)
assert(s.x == 0 and s.y == 0, 'fit view cannot be dragged offscreen')
s.mouseX, s.mouseY = 10, 20
view.Reset(s)
assert(s.zoom == 1 and s.x == 0 and s.y == 0 and s.mouseX == nil and s.mouseY == nil)
print('mark map transforms: anchored zoom, round trips, pan bounds, zoom limits and reset', true)
