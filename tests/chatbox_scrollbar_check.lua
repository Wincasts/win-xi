package.path = 'addons/chatbox/?.lua;' .. package.path
local bar = require('scrollbar')
assert(bar.Layout(10,20,120,10,10,0) == nil, 'no scrollbar when all rows fit')
assert(bar.Layout(10,20,20,100,10,0) == nil)
assert(bar.Width == 2 and bar.Reserve == 4 and bar.White[4] == 0.35 and bar.Bright[4] == 0.7,
    'inventory-style slim white thumb and brighter interaction state')
local bottom = bar.Layout(10,20,120,100,10,0)
assert(bottom.maximum == 90 and bottom.thumbBottom == 120 and bottom.thumbTop == 110)
local top = bar.Layout(10,20,120,100,10,90)
assert(top.thumbTop == 20 and top.thumbBottom == 30)
local middle = bar.Layout(10,20,120,100,10,45)
assert(middle.thumbTop == 65)
assert(bar.Hit(bottom,10,20) and not bar.Hit(bottom,15,20) and not bar.Hit(bottom,10,120))
assert(bar.Drag(bottom,25,5) == 90 and bar.Drag(bottom,115,5) == 0)
assert(bar.Drag(bottom,-100,9) == 90 and bar.Drag(bottom,1000,9) == 0, 'drag clamps outside bounds')
assert(bar.Page(bottom,40) == 10 and bar.Page(top,100) == 80)
assert(bar.Layout(0,0,5,100,1,50).thumbBottom <= 5, 'thumb stays inside very short tracks')
local model = require('log')
local history = model.New()
model.Add(history,'abcdefghijkl',1)
model.Add(history,'new',2)
local measured = 0
local function measure(text) measured=measured+1; return #text end
local metrics = model.Metrics(history,3,'font',12,measure)
assert(metrics.total == 5 and metrics.newer[1] == 1 and metrics.newer[2] == 5, 'counts wrapped visual rows, newest first')
local before = measured
assert(model.Metrics(history,3,'font',12,measure) == metrics and measured == before)
model.Add(history,'tail',1)
metrics = model.Metrics(history,3,'font',12,measure)
assert(metrics.total == 7 and metrics.newer[1] == 2)
local filtered = model.Metrics(history,3,'font',12,measure,{[2]=true})
assert(filtered.total == 1 and filtered.newer[1] == 1, 'channel tabs have their own range')
model.Clear(history)
assert(model.Metrics(history,3,'font',12,measure).total == 0, 'clear resets scrollbar metrics')
print('Chatbox scrollbar: overflow, thumb position/size, track paging, drag clamps, wrapped-row counts, cache and filters passed')
