local realpos, realpush, realpop = imgui.SetNextWindowPos, imgui.PushStyleVar, imgui.PopStyleVar;
local realpushcolor, realpopcolor = imgui.PushStyleColor, imgui.PopStyleColor;
local position, pivot, alpha, depth, color_depth, scale = nil, nil, nil, 0, 0, 1;
imgui.SetNextWindowPos = function(pos, cond, anchor) position = { pos[1], pos[2] }; pivot = { anchor[1], anchor[2] }; return realpos(pos, cond, anchor); end;
imgui.PushStyleVar = function(key, value) depth = depth + 1; if key == ImGuiStyleVar_Alpha then alpha = value; end; return realpush(key, value); end;
imgui.PopStyleVar = function(n) depth = depth - (n or 1); return realpop(n); end;
imgui.PushStyleColor = function(...) color_depth = color_depth + 1; return realpushcolor(...); end;
imgui.PopStyleColor = function(n) color_depth = color_depth - (n or 1); return realpopcolor(n); end;
local realfontpush, realfontpop, realcalc = imgui.PushFont, imgui.PopFont, imgui.CalcTextSize;
local fonts, sizes = {}, {};
imgui.PushFont = function(font, size)
    fonts[#fonts + 1] = scale;
    scale = size / 14; sizes[size] = true;
    return realfontpush(font, size);
end;
imgui.PopFont = function()
    assert(#fonts > 0, 'font stack underflow');
    scale = table.remove(fonts);
    return realfontpop();
end;
local measurements = 0;
imgui.CalcTextSize = function(words) measurements = measurements + 1; return #words * 7 * scale, 14 * scale; end;
