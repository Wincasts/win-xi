local layout=dofile('addons/chatbox/layout.lua')
local input=dofile('addons/chatbox/input.lua')
local state=layout.New()
local function plan(open,rect,match)
    local p=input.Layout(640,1920,1080,12,4,match and rect or nil)
    p.active,p.sourceRect=open,rect
    return p
end
local closed={20,700,660,1040}
local p=plan(false)
local box=layout.Arrange(state,closed,p,640,1920,1080,146,4,false)
assert(box.bottom==1040 and box.width==640)
p=plan(true)
box=layout.Arrange(state,closed,p,640,1920,1080,146,4,false)
assert(box.bottom==1020 and p.bottom==1040 and p.width==box.width,'opening input lifts log if native geometry has not moved yet')
local lifted={20,680,660,1020}
p=plan(true)
box=layout.Arrange(state,lifted,p,640,1920,1080,146,4,false)
assert(box.bottom==1020,'native lift is not applied twice')
p=plan(false)
box=layout.Arrange(state,closed,p,640,1920,1080,146,4,false)
assert(box.bottom==1040,'closing input returns to native base')
local native={0,1020,1920,1060}
p=plan(true,native,true)
box=layout.Arrange(state,lifted,p,640,1920,1080,146,4,true)
assert(box.left==0 and box.width==1920 and p.width==1920 and p.x==0 and box.bottom==1020)
assert(box.top==874,'clock target is the actual ten-row log top')
p=plan(false,nil,true)
box=layout.Arrange(state,closed,p,640,1920,1080,146,4,true)
assert(box.width==1920 and box.left==0,'native width persists while input is closed')
p=plan(false,nil,true)
box=layout.Arrange(state,{40,1400,1320,2080},p,640,3840,2160,146,4,true)
assert(box.width==3840 and box.left==0,'retained width ratio follows resolution/UI scale')
p=plan(true,native,false)
box=layout.Arrange(state,lifted,p,640,1920,1080,146,4,false)
assert(box.width==640 and p.width==640 and p.height==20,'custom mode also shares width')
assert(layout.Arrange(state,nil,p,640,1920,1080,146,4,false)==nil,'missing native anchor leaves native log')
assert(layout.Arrange(state,{20,0,660,100},p,640,1920,1080,146,4,false)==nil,'cannot fit ten rows')
p=plan(false)
local closedBefore=state.closedBottom
local full=layout.Expanded(layout.New(),{0,100,1920,1020},p,1920,1080,12,4,2)
assert(full.left==0 and full.top==100 and full.width==1920 and full.height==920 and full.rows==65,'before any compact layout, expanded page fills native bounds with whole rows')
full=layout.Expanded(state,{0,100,1920,1020},p,1920,1080,12,4,2)
assert(full.left==state.left and full.width==640 and full.top==100 and full.bottom==1020,'expanded log grows from the compact box\'s edges to the native height')
assert(p.width==full.width and state.closedBottom==closedBefore,'expanding never overwrites compact base')
assert(layout.Expanded(state,nil,p,1920,1080,12,4,2)==nil,'missing expanded bounds are not guessed')
assert(layout.Expanded(state,{0,0,640,140},p,1920,1080,12,4,2)==nil,'too-small expanded page stays native')
assert(layout.Fit(318,12,4,2)==22 and layout.Fit(146,12,4,2)==10 and layout.Fit(10,12,4,2)==0 and layout.Fit(0/0,12,4,2)==0,'whole rows that fit')
print('Chatbox layout: shared width, compact text, input lift without double movement, close/reset, native width retention and scale passed')
