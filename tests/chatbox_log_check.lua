package.path = 'addons/chatbox/?.lua;' .. package.path
local model = dofile('addons/chatbox/log.lua')
local function measure(text) return select(2, text:gsub('[^\128-\191]', '')) end
local function same(actual, expected)
    assert(#actual == #expected, table.concat(actual, '|'))
    for i, value in ipairs(expected) do assert(actual[i] == value, actual[i] .. ' ~= ' .. value) end
end
assert(model.Rows == 10)
local wheelLog = model.New()
model.Add(wheelLog, 'abcdefghijkl', 1)
local wheelRows, offset, overflow = model.Tail(wheelLog, 3, 'font', 12, measure, 2, nil, 0, 1)
assert(wheelRows[1].text == 'def' and wheelRows[2].text == 'ghi' and offset == 1 and overflow,
    'wheel offset counts visual rows, even within a single wrapped message')
wheelRows, offset = model.Tail(wheelLog, 3, 'font', 12, measure, 2, nil, 0, 999)
assert(wheelRows[1].text == 'abc' and wheelRows[2].text == 'def' and offset == 2, 'oldest offset is clamped')
local cachedRows, cachedOffset = model.Tail(wheelLog, 3, 'font', 12, function() error('wheel cache missed') end, 2, nil, 0, 999)
assert(cachedRows == wheelRows and cachedOffset == 2, 'wheel offset is part of the layout cache')
wheelRows, offset = model.Tail(wheelLog, 3, 'font', 12, measure, 2, nil, 0, -4)
assert(wheelRows[2].text == 'jkl' and offset == 0, 'negative wheel offsets clamp to newest')
model.Add(wheelLog, 'hidden channel', 2)
wheelRows = model.Tail(wheelLog, 3, 'font', 12, measure, 2, {[1]=true}, 0, 1)
assert(wheelRows[2].text == 'ghi', 'channel filtering happens before row-based scrolling')
assert(model.Clean('\30\81hello\31\01 world\127\49\1!\7') == 'hello world!\n')
assert(model.Clean('\129\92\130\160') == '\129\92\130\160', 'SJIS backslash trail byte preserved')
assert(model.Clean('a\tb\r\nc') == 'a b\nc')
assert(model.Clean('Hill\129\64Lizard') == 'Hill Lizard', 'FFXI ideographic name space becomes a regular space')
assert(model.Clean('Goblin\129\64\129\64Smithy') == 'Goblin  Smithy', 'spacing is preserved, not collapsed')
assert(model.Clean('\130\129\64') == '\130\129\64', 'space-like byte pairs spanning SJIS characters are not replaced')
assert(model.Clean('Hill?Lizard') == 'Hill?Lizard', 'real question marks are untouched')
assert(model.Clean('Stalking\129\63Sapling') == 'Stalking Sapling', 'live 81 3F enemy-name separator')
assert(model.Clean('\130\129\63') == '\130\129\63', '81 3F spanning a valid SJIS pair and a real question mark is untouched')
assert(model.Clean('\31\129?') == '?', 'palette operand 81 followed by a real question mark is not a name separator')
assert(model.Clean('a\239\42b\239\77c') == 'abc', 'the game\'s other pictographs, EF 29 to EF 4D, show nothing')
same(model.Wrap('one two three', 7, measure), {'one two', 'three'})
same(model.Wrap('abcdefghijkl', 4, measure), {'abcd','efgh','ijkl'})
same(model.Wrap('猫犬鳥魚', 2, measure), {'猫犬','鳥魚'})
same(model.Wrap('猫犬', 0, measure), {'猫','犬'})
same(model.Wrap('one\ntwo\n\nthree', 20, measure), {'one','two','','three'})
local log = model.New()
assert(not model.Add(log, '', 1) and not model.Add(log, string.rep('x', 8193), 1))
for i=1,12 do model.Add(log, 'line ' .. i, i) end
local rows = model.Tail(log, 80, 'font', 14, measure)
assert(#rows == 10 and rows[1].text == 'line 3' and rows[10].mode == 12)
assert(model.Tail(log, 80, 'font', 14, function() error('cache missed') end) == rows)
assert(model.Tail(log, 80, 'font2', 14, measure) ~= rows, 'font change rewraps')
rows = model.Tail(log, 80, 'font', 16, measure)
assert(model.Tail(log, 40, 'font', 16, measure) ~= rows, 'width change rewraps')
model.Clear(log)
model.Add(log, string.rep('字', 31), 4)
rows = model.Tail(log, 3, 'font', 14, measure)
assert(#rows == 10 and rows[10].text == '字' and rows[1].text == '字字字')
for i=1,300 do model.Add(log, tostring(i), 1) end
assert(#log.messages == 256 and log.messages[1].text == '45')
local expanded=model.Tail(log,80,'font',14,measure,40)
assert(#expanded==40 and expanded[1].text=='261' and expanded[40].text=='300','expanded row count reveals more retained messages')
assert(model.Tail(log,80,'font',14,function() error('expanded cache missed') end,40)==expanded)
rows=model.Tail(log,80,'font',14,measure)
assert(#rows==10 and rows[1].text=='291' and rows~=expanded,'collapse invalidates expanded cache and restores ten rows')
model.Clear(log); assert(#model.Tail(log, 80, 'font', 14, measure) == 0)
local dialogue = model.New()
assert(model.Add(dialogue, 'NPC: Welcome!', 150, 10))
assert(dialogue.messages[1].text == 'NPC [NPC]: Welcome!', 'NPC tag follows speaker name')
local revision = dialogue.revision
assert(not model.Add(dialogue, 'NPC: Welcome!', 151, 10.1))
assert(not model.Add(dialogue, 'NPC: Welcome!', 150, 10.2))
assert(#dialogue.messages == 1 and dialogue.revision == revision, 'triplicated dialogue kept once without invalidating layout')
assert(model.Add(dialogue, 'NPC: Another line.', 151, 10.3), 'distinct dialogue is preserved')
assert(model.Add(dialogue, 'NPC: Welcome!', 150, 12), 'same dialogue later is legitimate')
assert(model.Add(dialogue, 'remapped NPC line', 1, 13, 150))
assert(not model.Add(dialogue, 'remapped NPC line', 1, 13.1, 151), 'original NPC mode survives formatter remapping')
for _, mode in ipairs({1, 12, 36, 121, 131, 142}) do
    assert(model.Add(dialogue, 'repeat', mode, 14))
    assert(model.Add(dialogue, 'repeat', mode, 14), 'non-dialogue repeats must not be suppressed')
end
model.Add(dialogue, '[12:34:56] Moogle : Hello!', 150, 15)
assert(dialogue.messages[#dialogue.messages].text == '[12:34:56] Moogle [NPC]: Hello!', 'timestamp is not mistaken for the name')
model.Add(dialogue, 'Moogle [npc]: Hello!', 150, 17)
assert(dialogue.messages[#dialogue.messages].text == 'Moogle [NPC]: Hello!', 'legacy tag is uppercased, not duplicated')
model.Add(dialogue, 'Moogle [NPC]: Hello!', 150, 17.1)
assert(dialogue.messages[#dialogue.messages].text == 'Moogle [NPC]: Hello!', 'uppercase tag is not duplicated')
model.Add(dialogue, 'Player: Hello!', 1, 18)
assert(dialogue.messages[#dialogue.messages].text == 'Player: Hello!', 'players are not tagged')
model.Add(dialogue, 'Anonymous dialogue.', 151, 19)
assert(dialogue.messages[#dialogue.messages].text == 'Anonymous dialogue.', 'unnamed dialogue is unchanged')
model.Clear(dialogue)
assert(model.Add(dialogue, 'remapped NPC line', 150, 13.2), 'clear resets dialogue replay tracking')

-- timestamps hidden: each line shown without the stamp at its start, the messages keeping theirs
local plainText, plainSpans = 'no stamp here', { {first=1,last=2,bank=30,slot=5} }
local sameText, sameSpans = model.Unstamp(plainText, plainSpans)
assert(sameText == plainText and sameSpans == plainSpans, 'a line without a stamp: the same text and spans back')
local stampedSpans = { {first=1,last=10,bank=30,slot=81}, {first=12,last=17,bank=30,slot=5} }
local body, bodySpans = model.Unstamp('[23:55:59] Hamelin : hi', stampedSpans)
assert(body == 'Hamelin : hi', 'the stamp and the space after it taken off: ' .. body)
assert(#bodySpans == 1 and bodySpans[1].first == 1 and bodySpans[1].last == 6 and bodySpans[1].slot == 5, 'the stamp\'s own colour gone, the rest moved up')
assert(model.Unstamp('[11:55 PM] twelve hour') == 'twelve hour', 'Ashita\'s twelve-hour stamps too')
assert(model.Unstamp('[01:00:00] first\n[01:00:00]   second\nthird') == 'first\nsecond\nthird', 'every stamped line of a message, however it is spaced')
assert(model.Unstamp('[01:00:00] ') == '[01:00:00] ', 'nothing but a stamp is left as it is')
assert(select(2, model.Unstamp('[01:00:00] bare', nil)) == nil, 'no spans in, none out')
local stampLog = model.New()
model.Add(stampLog, '[23:55:59] Hamelin : hi', 9, nil, 9, stampedSpans)
model.Add(stampLog, '[23:56:00] abcdefghijkl', 1)
local stampRows = model.Tail(stampLog, 12, 'font', 12, measure, 10)
assert(#stampRows == 4 and stampRows[1].text == '[23:55:59]' and stampRows[2].text == 'Hamelin : hi' and stampRows[4].text == 'abcdefghijkl', 'shown to begin with, wrapped with them')
model.ShowStamps(stampLog, false)
stampRows = model.Tail(stampLog, 12, 'font', 12, measure, 10)
assert(#stampRows == 2 and stampRows[1].text == 'Hamelin : hi' and stampRows[2].text == 'abcdefghijkl', 'hidden: the lines wrapped without them: ' .. #stampRows)
assert(stampRows[1].spans[1].first == 1 and stampRows[1].spans[1].last == 6 and stampRows[1].spans[1].slot == 5, 'the rows\' spans moved with the text')
assert(model.Metrics(stampLog, 12, 'font', 12, measure).total == 2, 'the metrics count the rows as shown')
assert(stampLog.messages[1].text == '[23:55:59] Hamelin : hi', 'the message keeps its stamp')
local revision = stampLog.revision
model.ShowStamps(stampLog, false)
assert(stampLog.revision == revision, 'the same choice again changes nothing')
model.ShowStamps(stampLog, true)
stampRows = model.Tail(stampLog, 12, 'font', 12, measure, 10)
assert(#stampRows == 4 and stampRows[1].text == '[23:55:59]' and stampRows[2].text == 'Hamelin : hi', 'shown again at once')
model.ShowStamps(stampLog, false)
model.Clear(stampLog)
model.Add(stampLog, '[00:00:01] after a clear', 1)
assert(model.Tail(stampLog, 40, 'font', 12, measure, 10)[1].text == 'after a clear', 'the choice outlives a clear')
-- Each row's offset: where its text starts in the message's text as shown, with the stamps or without them; the
-- message's tokens kept on it, from Add and from Prepend
local linkLog = model.New()
local linkTokens = { { kind = 'item', id = 1 } }
model.Add(linkLog, '[01:02:03] abcd efgh ijkl', 1, nil, nil, nil, nil, linkTokens)
assert(linkLog.messages[1].tokens == linkTokens, 'the tokens kept on the message')
model.Add(linkLog, 'no links', 1)
assert(linkLog.messages[2].tokens == nil, 'none given: none kept')
local offsetRows = model.Tail(linkLog, 4, 'font', 12, measure, 10)
for _, row in ipairs(offsetRows) do
    local whole = row.message.text
    assert(whole:sub(row.offset, row.offset + #row.text - 1) == row.text, 'stamped: the row at its offset: ' .. row.text)
end
assert(#offsetRows == 9 and offsetRows[4].text == 'abcd' and offsetRows[4].offset == 12, 'past the stamp and the space after it')
model.ShowStamps(linkLog, false)
offsetRows = model.Tail(linkLog, 4, 'font', 12, measure, 10)
local shownText = model.Shown(linkLog, linkLog.messages[1])
assert(shownText == 'abcd efgh ijkl' and offsetRows[1].text == 'abcd' and offsetRows[1].offset == 1
    and offsetRows[2].offset == 6 and offsetRows[3].offset == 11, 'stamps hidden: the offsets in the text as shown')
assert(model.Shown(linkLog, linkLog.messages[2]) == 'no links', 'a message without a stamp shown whole')
model.Prepend(linkLog, { { text = 'older', mode = 1, tokens = linkTokens }, { text = 'oldest', mode = 1, tokens = 'x' } })
assert(linkLog.messages[1].tokens == linkTokens and linkLog.messages[2].tokens == nil, 'the history\'s tokens kept; anything else not')
print('Chatbox model: 10-row tail, bounds, CP932 controls, wrapping, UTF-8, cache invalidation, hidden timestamps, row offsets and tokens passed')
