local imgui = require('imgui');
local catalog = require('map_catalog');
local view = require('debug_view');
local path = os.tmpname(); os.remove(path);
local e = require('boundary_editor').new(catalog, path);
e.edit_mode[1] = true;
local scroll_x, scroll_y = 0, 0;
local mouse = { x = 0, y = 0, clicked = false, down = false, button = 'Center selected vertex' };
imgui.GetCursorScreenPos = function() return 10 - scroll_x, 20 - scroll_y; end;
imgui.SetScrollX = function(value) scroll_x = value; end;
imgui.SetScrollY = function(value) scroll_y = value; end;
imgui.GetMousePos = function() return mouse.x, mouse.y; end;
imgui.IsMouseClicked = function() return mouse.clicked; end;
imgui.IsMouseDown = function() return mouse.down; end;
imgui.IsItemHovered = function() return true; end;
imgui.Button = function(label) return label == mouse.button; end;
local child_visible, horizontal, child_count = true, false, 0;
imgui.BeginChild = function(_, _, _, flags) child_count = child_count + 1; horizontal = bit.band(flags, 2048) ~= 0; return child_visible; end;
local s = { debug = true, enabled = true, zone = 100, map_key = catalog[100].key,
    map_x = 238, map_y = 337, approach_yalms = 30, approach_pixels = 30 };
local checks = 0;
local function check(label, ok) H.print(label, ok); assert(ok, label); checks = checks + 1; end
view.browser.follow[1] = true; view.zoom[1] = 2;
view.draw(s, e); mouse.button = nil;
check('zoom canvas has horizontal scrollbar support', horizontal);
check('center selected vertex scrolls zoomed canvas', scroll_x == 196 and scroll_y == 406);
local point = e.selected.polygon[1];
mouse.x, mouse.y = 10 - scroll_x + point[1] * 2 + 3, 20 - scroll_y + point[2] * 2 + 2;
mouse.clicked, mouse.down = true, true;
view.draw(s, e);
check('hit test uses scaled coordinates and screen-sized handle radius', e.dragging and e.dragging.index == 1);
check('off-center click does not move vertex', point[1] == e.selected.polygon[1][1] and point[2] == e.selected.polygon[1][2]);
mouse.clicked = false; mouse.x, mouse.y = mouse.x + 20, mouse.y + 12;
view.draw(s, e);
check('zoomed/scrolled drag converts back to reference pixels', e.selected.polygon[1][1] == 236 and e.selected.polygon[1][2] == 337);
mouse.down = false; view.draw(s, e);
check('zoomed release commits normally', not e.dragging and e.revision == 1);
check('zoom does not alter other stored vertices', e.selected.polygon[2][1] == 237 and e.selected.polygon[2][2] == 330);
e:begin(1); e:move(234, 336); view.zoom[1] = 3;
-- Slider changes during draw, rather than changing zoom before previous_zoom is sampled.
imgui.SliderFloat = function(_, zoom) zoom[1] = 4; return true; end;
view.draw(s, e);
check('zoom changes cancel unfinished drag safely', not e.dragging and e.selected.polygon[1][1] == 236);
imgui.SliderFloat = function() return false; end;
mouse.button = 'Reset view'; view.draw(s, e); mouse.button = nil;
check('reset restores 1x and clears scrolling', view.zoom[1] == 1 and scroll_x == 0 and scroll_y == 0);
e:begin(1); e:move(234, 336); child_visible = false; view.draw(s, e);
check('clipped child cancels unfinished drag', not e.dragging and not s.editing);
check('EndChild is called for clipped child too', H.calls.EndChild == child_count);
view.clear(); os.remove(path); os.remove(path .. '.tmp'); os.remove(path .. '.bak');
