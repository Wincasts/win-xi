#!/usr/bin/env python3
"""Generate MobDB data files from a Phoenix / LandSandBoat server that keeps its mobs in YAML.

The Lua importers bundled with MobDB read the old mob_*.sql dumps. This server loads mobs from
data/zones/<zone>/mobs.yaml and data/ecosystems.yaml instead, so this script reads those the same
way the map server does and writes data/<zoneId>.lua files in the format MobDB already loads.

    python import_phoenix.py --server /path/to/Phoenix-beta --out /path/to/mobdb-config/output

Copy the generated files over Ashita/addons/mobdb/data afterwards.
Requires PyYAML (pip install pyyaml).
"""

import argparse
import collections
import copy
import glob
import json
import os
import re
import sys

import yaml

LOADER = getattr(yaml, 'CSafeLoader', yaml.SafeLoader)
HERE = os.path.dirname(os.path.abspath(__file__))
GENERATED_HEADER = '--Generated by import_phoenix.py'

# Server immunity names -> the bits MobDB's icons are keyed on (tokens.lua, PrintImmunities).
# Immunities MobDB has no icon for (addle, aspir, terror, dispel, plague, curse) are dropped.
IMMUNITY_BITS = {
    'gravity': 0x02, 'bind': 0x04, 'stun': 0x08, 'silence': 0x10, 'paralyze': 0x20, 'blind': 0x40,
    'slow': 0x80, 'poison': 0x100, 'elegy': 0x200, 'requiem': 0x400, 'light_sleep': 0x800,
    'dark_sleep': 0x1000, 'petrify': 0x2000,
}

# Fallback for scripts/combat/skillchain.lua's resistanceRankMultiplier, used if it cannot be parsed.
RANK_MULTIPLIER = {
    -3: 1.50, -2: 1.30, -1: 1.15, 0: 1.00, 1: 0.85, 2: 0.70, 3: 0.60, 4: 0.50,
    5: 0.40, 6: 0.30, 7: 0.25, 8: 0.20, 9: 0.15, 10: 0.10, 11: 0.05,
}

PHYSICAL = (('Slashing', 'slashing'), ('Piercing', 'piercing'), ('H2H', 'h2h'), ('Impact', 'blunt'))
ELEMENTS = (('Fire', 'fire'), ('Ice', 'ice'), ('Wind', 'wind'), ('Earth', 'earth'),
            ('Lightning', 'thunder'), ('Water', 'water'), ('Light', 'light'), ('Dark', 'dark'))


def normalize(name):
    return re.sub(r'[^a-z0-9]', '', str(name).lower())


def load_yaml(path):
    with open(path, encoding='utf-8') as handle:
        return yaml.load(handle, Loader=LOADER) or {}


def merge_patch(target, patch):
    """RFC 7386, which is what the server's mergeYaml applies: maps merge, null deletes, the rest replaces."""
    if not isinstance(patch, dict):
        return copy.deepcopy(patch)
    result = dict(target) if isinstance(target, dict) else {}
    for key, value in patch.items():
        if value is None:
            result.pop(key, None)
        else:
            result[key] = merge_patch(result.get(key), value)
    return result


def overlay(base, override):
    """Attribute chain merge (ecosystem -> family -> species -> template -> spawn): maps merge, the rest replaces."""
    if not isinstance(base, dict) or not isinstance(override, dict):
        return override
    result = dict(base)
    for key, value in override.items():
        result[key] = overlay(result[key], value) if key in result else value
    return result


def read_init(server):
    """Uncommented modules/init.txt entries, in order."""
    path = os.path.join(server, 'modules', 'init.txt')
    if not os.path.exists(path):
        return []
    with open(path, encoding='utf-8') as handle:
        lines = [line.strip() for line in handle]
    return [line for line in lines if line and not line.startswith('#')]


def read_settings(server, overrides):
    settings = {}
    for path in (os.path.join(server, 'settings', 'default', 'main.lua'), os.path.join(server, 'settings', 'main.lua')):
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8', errors='replace') as handle:
            for line in handle:
                match = re.match(r'\s*([A-Z][A-Z0-9_]*)\s*=\s*([^,\s]+)\s*,', line)
                if match:
                    settings[match.group(1)] = match.group(2)
    for entry in overrides:
        key, _, value = entry.partition('=')
        settings[key.strip()] = value.strip()

    def number(key):
        value = settings.get(key, '0')
        if value in ('true', 'false'):
            return int(value == 'true')
        try:
            return int(float(value))
        except ValueError:
            return 0

    return number


def sql_rows(path):
    """Yield (table, [raw column strings]) for each single-row INSERT/REPLACE in a LandSandBoat style SQL file."""
    if not os.path.exists(path):
        return
    with open(path, encoding='utf-8', errors='replace') as handle:
        for line in handle:
            match = re.match(r"\s*(?:INSERT|REPLACE) INTO `(\w+)` VALUES \((.*)\);", line)
            if not match:
                continue
            columns = [a or b for a, b in re.findall(r"'((?:[^'\\]|\\.|'')*)'|([^,]+)", match.group(2))]
            yield match.group(1), [column.strip() for column in columns]


def load_name_ids(server, core_file, table, module_sql):
    """name -> id from a table whose first two columns are an id and (somewhere early) a name."""
    names = {}
    for path in [os.path.join(server, 'sql', core_file)] + module_sql:
        for found, columns in sql_rows(path):
            if found != table:
                continue
            identifier = int(columns[0])
            if table == 'item_basic':
                names[columns[2]] = identifier
            else:
                names[columns[1]] = identifier
    return names


def load_spell_lists(server, module_sql):
    lists = collections.defaultdict(dict)  # list id -> spell id -> [min, max]
    for found, columns in sql_rows(os.path.join(server, 'sql', 'mob_spell_lists.sql')):
        lists[int(columns[1])][int(columns[2])] = [int(columns[3]), int(columns[4])]

    skipped = 0
    for path in module_sql:
        with open(path, encoding='utf-8', errors='replace') as handle:
            for line in handle:
                line = line.split('--')[0].strip()
                if '`mob_spell_lists`' not in line:
                    continue
                where = dict(re.findall(r"`(spell_list_id|spell_id)`\s*=\s*(\d+)", line.split('WHERE')[-1])) if 'WHERE' in line else {}
                list_id = int(where['spell_list_id']) if 'spell_list_id' in where else None
                spell_id = int(where['spell_id']) if 'spell_id' in where else None
                if line.startswith('UPDATE') and list_id is not None and spell_id is not None:
                    entry = lists[list_id].get(spell_id)
                    for column, value in re.findall(r"`(min_level|max_level)`\s*=\s*(\d+)", line.split('WHERE')[0]):
                        if entry:
                            entry[0 if column == 'min_level' else 1] = int(value)
                elif line.startswith('DELETE') and list_id is not None:
                    if spell_id is None:
                        lists.pop(list_id, None)
                    else:
                        lists[list_id].pop(spell_id, None)
                elif line.startswith(('INSERT', 'REPLACE')):
                    for found, columns in sql_rows_from_line(line):
                        lists[int(columns[1])][int(columns[2])] = [int(columns[3]), int(columns[4])]
                else:
                    skipped += 1
    return lists, skipped


def sql_rows_from_line(line):
    match = re.match(r"\s*(?:INSERT|REPLACE) INTO `(\w+)` VALUES \((.*)\);", line)
    if match:
        columns = [a or b for a, b in re.findall(r"'((?:[^'\\]|\\.|'')*)'|([^,]+)", match.group(2))]
        yield match.group(1), [column.strip() for column in columns]


def load_rank_multipliers(server):
    path = os.path.join(server, 'scripts', 'combat', 'skillchain.lua')
    try:
        with open(path, encoding='utf-8', errors='replace') as handle:
            text = handle.read()
        block = re.search(r'local resistanceRankMultiplier\s*=\s*\{(.*?)\}', text, re.S).group(1)
        table = {int(rank): float(value) for rank, value in re.findall(r'\[\s*(-?\d+)\]\s*=\s*([\d.]+)', block)}
        return table or RANK_MULTIPLIER
    except (OSError, AttributeError):
        return RANK_MULTIPLIER


def load_species(server, top_modules):
    document = load_yaml(os.path.join(server, 'data', 'ecosystems.yaml'))
    for module in top_modules:
        path = os.path.join(server, 'modules', module, 'data', 'ecosystems.yaml')
        if os.path.exists(path):
            document = merge_patch(document, load_yaml(path))

    species = {}
    for ecosystem in (document.get('ecosystems') or {}).values():
        ecosystem_attributes = ecosystem.get('attributes') or {}
        for family in (ecosystem.get('families') or {}).values():
            family_attributes = overlay(ecosystem_attributes, family.get('attributes') or {})
            for name, entry in (family.get('species') or {}).items():
                species[name] = overlay(family_attributes, entry.get('attributes') or {})
    return species


def build_client_names(stock_dir):
    """normalized name -> client spelling, per zone and overall, from stock MobDB data (whose names came from the client DATs)."""
    zones, everywhere = {}, {}
    for path in glob.glob(os.path.join(stock_dir, '*.lua')):
        with open(path, encoding='utf-8', errors='replace') as handle:
            text = handle.read()
        if text.startswith(GENERATED_HEADER):
            continue
        names = {}
        for raw in re.findall(r"Name='((?:[^'\\]|\\.)*)'", text):
            name = raw.replace("\\'", "'")
            names.setdefault(normalize(name), name)
        zones[os.path.basename(path)[:-4]] = names
        for key, name in names.items():
            everywhere.setdefault(key, name)
    return {'zones': zones, 'all': everywhere}


def lua_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


def lua_number(value):
    return ('%f' % value).rstrip('0').rstrip('.')


def lua_bool(value):
    return 'true' if value else 'false'


class Generator:
    def __init__(self, args):
        self.args = args
        self.server = args.server
        self.stats = collections.Counter()
        self.warnings = collections.Counter()

        init = read_init(self.server)
        self.setting = read_settings(self.server, args.set)

        # GetDataModules only looks at the leading path segment of each init.txt entry.
        top_modules = list(dict.fromkeys(entry.split('/')[0] for entry in init))
        module_sql = []
        self.zone_overlay_dirs = []
        for entry in init:
            path = os.path.join(self.server, 'modules', entry)
            if os.path.isdir(path):
                module_sql += sorted(glob.glob(os.path.join(path, '*.sql')))
                if os.path.isdir(os.path.join(path, 'zones')):
                    self.zone_overlay_dirs.append(os.path.join(path, 'zones'))
            elif path.endswith('.sql') and os.path.exists(path):
                module_sql.append(path)
        if args.no_module_data:
            self.zone_overlay_dirs = []

        self.items = load_name_ids(self.server, 'item_basic.sql', 'item_basic', module_sql)
        self.spells = load_name_ids(self.server, 'spell_list.sql', 'spell_list', module_sql)
        self.spell_lists, skipped = load_spell_lists(self.server, module_sql)
        if skipped:
            self.warnings['module mob_spell_lists statements not understood'] += skipped
        self.rank_multiplier = load_rank_multipliers(self.server)
        self.species = load_species(self.server, top_modules)
        self.zone_ids = load_yaml(os.path.join(self.server, 'data', 'enums', 'zone.yaml'))['values']
        self.jobs = load_yaml(os.path.join(self.server, 'data', 'enums', 'job.yaml'))['values']

        with open(args.names, encoding='utf-8') as handle:
            self.client_names = json.load(handle)

        self.restrict_content = bool(self.setting('RESTRICT_CONTENT'))
        self.level_cap_min = self.setting('NORMAL_MOB_MAX_LEVEL_RANGE_MIN')
        self.level_cap_max = self.setting('NORMAL_MOB_MAX_LEVEL_RANGE_MAX')

    def content_enabled(self, tag):
        if not tag or not self.restrict_content:
            return True
        return bool(self.setting('ENABLE_' + str(tag).upper()))

    def load_zone(self, zone):
        document = load_yaml(os.path.join(self.server, 'data', 'zones', zone, 'mobs.yaml'))
        for directory in self.zone_overlay_dirs:
            path = os.path.join(directory, zone, 'mobs.yaml')
            if os.path.exists(path):
                document = merge_patch(document, load_yaml(path))
                self.stats['module overlay files applied'] += 1
        return document

    def client_name(self, zone_id, template_name, template, spawn):
        """Resolve the name the client shows. Returns (name, verified against client data)."""
        candidates = [template.get('display_name'), spawn.get('script'), template_name]
        zone_names = self.client_names['zones'].get(str(zone_id), {})
        for known in (zone_names, self.client_names['all']):
            for candidate in candidates:
                if candidate and normalize(candidate) in known:
                    return known[normalize(candidate)], True
        fallback = template.get('display_name') or spawn.get('script') or template_name
        return str(fallback).replace('_', ' '), False

    def drops(self, template_name, loot):
        found = []

        def add(name):
            if name == 'nothing':
                return
            item = self.items.get(str(name))
            if item is None:
                self.warnings['unknown item name: %s' % name] += 1
            elif item not in found:
                found.append(item)

        for roll in loot.get('drops') or []:
            if 'item' in roll:
                add(roll['item'])
            for name in roll.get('one_of') or []:
                add(name)
        if self.args.include_steal:
            steal = loot.get('steal') or []
            for name in ([steal] if isinstance(steal, str) else steal):
                add(name)
            for name in loot.get('despoil') or {}:
                add(name)
        return found

    def spell_ids(self, template, low, high):
        if template.get('spells'):
            found = []
            for name in template['spells']:
                spell = self.spells.get(str(name))
                if spell is None:
                    self.warnings['unknown spell name: %s' % name] += 1
                else:
                    found.append(spell)
            return sorted(found)
        entries = self.spell_lists.get(template.get('spell_list_id') or 0, {})
        return sorted(spell for spell, (minimum, maximum) in entries.items() if low <= maximum and high >= minimum)

    def modifiers(self, resists):
        physical = resists.get('dmg_physical') or {}
        magic = resists.get('dmg_magic') or {}
        ranks = resists.get('rank_element') or {}
        result = {}
        for label, key in PHYSICAL:
            result[label] = 1 + (physical.get(key) or 0) / 10000.0
        for label, key in ELEMENTS:
            rank = max(-3, min(11, ranks.get(key) or 0))
            taken = (1 + (magic.get('all') or 0) / 10000.0) * (1 + (magic.get(key) or 0) / 10000.0)
            if self.args.elements == 'rank':
                taken *= self.rank_multiplier.get(rank, 1.0)
            result[label] = round(taken, 4)
        return result

    def build_entry(self, template, spawn):
        attributes = overlay(self.species.get(str(template.get('species')), {}), template.get('attributes') or {})
        attributes = overlay(attributes, spawn.get('attributes') or {})
        if str(template.get('species')) not in self.species:
            self.warnings['unknown species: %s' % template.get('species')] += 1

        behaviors = attributes.get('behaviors') or {}
        resists = attributes.get('resists') or {}
        detects = set(attributes.get('detects') or [])
        notorious = 'notorious' in (template.get('type') or [])

        low, high = (list(spawn.get('level') or [0, 0]) + [0, 0])[:2]
        if not notorious:
            if self.level_cap_min > 0 and low > self.level_cap_min:
                low = self.level_cap_min
            if self.level_cap_max > 0 and high > self.level_cap_max:
                high = self.level_cap_max

        jobs = attributes.get('jobs') or []
        main_job = self.jobs.get(str(jobs[0]), 0) if jobs else 0
        sub_job = self.jobs.get(str(jobs[1]), 0) if len(jobs) > 1 else 0

        immunities = 0
        for name in resists.get('immune_status') or []:
            immunities |= IMMUNITY_BITS.get(str(name), 0)

        return {
            'Notorious': notorious,
            'Aggro': bool(behaviors.get('aggressive')),
            'Link': bool(behaviors.get('links')),
            'TrueSight': bool(behaviors.get('true_detection')),
            'Job': main_job,
            'SubJob': sub_job if sub_job != main_job else 0,
            'MinLevel': low,
            'MaxLevel': high,
            'Immunities': immunities,
            'Respawn': (attributes.get('spawn') or {}).get('respawn') or 0,
            'Sight': 'sight' in detects,
            'Sound': 'hearing' in detects,
            'Blood': 'lowhp' in detects,
            'Magic': 'magic' in detects,
            'JA': 'ability' in detects,
            'Scent': 'scent' in detects,
            'Drops': self.drops(None, template.get('loot') or {}),
            'Spells': self.spell_ids(template, low, high),
            'Modifiers': self.modifiers(resists),
        }

    @staticmethod
    def format_entry(name, entry):
        parts = ['Name=%s' % lua_string(name)]
        for key in ('Notorious', 'Aggro', 'Link', 'TrueSight'):
            parts.append('%s=%s' % (key, lua_bool(entry[key])))
        parts.append('Job=%d' % entry['Job'])
        if entry['SubJob']:
            parts.append('SubJob=%d' % entry['SubJob'])
        for key in ('MinLevel', 'MaxLevel', 'Immunities', 'Respawn'):
            parts.append('%s=%d' % (key, entry[key]))
        for key in ('Sight', 'Sound', 'Blood', 'Magic', 'JA', 'Scent'):
            parts.append('%s=%s' % (key, lua_bool(entry[key])))
        parts.append('Drops={%s}' % ','.join(str(item) for item in entry['Drops']))
        parts.append('Spells={%s}' % ','.join(str(spell) for spell in entry['Spells']))
        modifiers = ', '.join('%s=%s' % (label, lua_number(entry['Modifiers'][label])) for label, _ in PHYSICAL + ELEMENTS)
        parts.append('Modifiers={%s}' % modifiers)
        return '{ %s },' % ', '.join(parts)

    def generate_zone(self, zone):
        zone_id = self.zone_ids.get(zone)
        if zone_id is None:
            self.warnings['zone folder not in zone.yaml: %s' % zone] += 1
            return False

        document = self.load_zone(zone)
        templates = document.get('templates') or {}
        by_name = collections.defaultdict(list)  # client name -> [(index, key, entry, verified)]

        for mob_id, spawn in sorted((document.get('spawns') or {}).items()):
            spawn = spawn or {}
            template_name = spawn.get('template')
            # A spawn with no template is disabled. One with a template but no placement is kept: the zone
            # does not instantiate it, but battlefields, instances and scripts bring it in at that index.
            if not template_name:
                self.stats['spawns skipped (no template, disabled)'] += 1
                continue
            template = templates.get(template_name)
            if template is None:
                self.warnings['spawn references unknown template: %s/%s' % (zone, template_name)] += 1
                continue
            if not self.content_enabled(template.get('content')):
                self.stats['spawns skipped (content disabled)'] += 1
                continue

            entry = self.build_entry(template, spawn)
            name, verified = self.client_name(zone_id, template_name, template, spawn)
            key = json.dumps(entry, sort_keys=True)
            by_name[name].append((int(mob_id) & 0xFFF, key, entry, verified))
            self.stats['spawns written'] += 1
            if not verified:
                self.stats['spawns whose client name is a guess (always written by index)'] += 1

        if not by_name:
            return False

        names, indices = {}, {}
        for name, spawns in by_name.items():
            # The most common variant becomes the by-name entry; anything else is pinned to its index.
            common_key = collections.Counter(key for _, key, _, _ in spawns).most_common(1)[0][0]
            for index, key, entry, verified in spawns:
                if key == common_key:
                    names[name] = entry
                if key != common_key or not verified:
                    indices[index] = (name, entry)

        path = os.path.join(self.args.out, '%u.lua' % zone_id)
        with open(path, 'w', encoding='utf-8', newline='\n') as output:
            output.write(GENERATED_HEADER + '\n')
            output.write('--Zone: %s\n' % zone)
            output.write('--Zone ID: %u\n' % zone_id)
            output.write('return {\n    Names = {\n')
            for name in sorted(names):
                output.write('        [%s] = %s\n' % (lua_string(name), self.format_entry(name, names[name])))
            output.write('    },\n    Indices = {\n')
            for index in sorted(indices):
                name, entry = indices[index]
                output.write('        [%d] = %s\n' % (index, self.format_entry(name, entry)))
            output.write('    },\n};')

        self.stats['zones written'] += 1
        self.stats['name entries'] += len(names)
        self.stats['index entries'] += len(indices)
        return True

    def run(self):
        os.makedirs(self.args.out, exist_ok=True)
        zones = sorted(os.path.basename(os.path.dirname(path))
                       for path in glob.glob(os.path.join(self.server, 'data', 'zones', '*', 'mobs.yaml')))
        if self.args.zone:
            zones = [zone for zone in zones if zone in self.args.zone]
        for zone in zones:
            self.generate_zone(zone)

        print('Settings: RESTRICT_CONTENT=%d, normal mob level cap min/max=%d/%d, module zone overlays=%d folders' % (
            self.restrict_content, self.level_cap_min, self.level_cap_max, len(self.zone_overlay_dirs)))
        for key, value in self.stats.items():
            print('%8d  %s' % (value, key))
        if self.warnings:
            print('Warnings:')
            for key, value in self.warnings.most_common(40):
                print('%8d  %s' % (value, key))
            if len(self.warnings) > 40:
                print('          ... and %d more kinds' % (len(self.warnings) - 40))
        print('Output: %s' % self.args.out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--server', help='Path to the server checkout (the folder holding data/, sql/ and modules/).')
    parser.add_argument('--out', help='Folder to write <zoneId>.lua files into.')
    parser.add_argument('--names', default=os.path.join(HERE, 'client_names.json'),
                        help='Client name dictionary. Defaults to client_names.json beside this script.')
    parser.add_argument('--build-names', metavar='STOCK_DATA_DIR',
                        help='Rebuild the client name dictionary from a folder of stock MobDB data files, then exit.')
    parser.add_argument('--zone', action='append', help='Only generate this zone folder name. Repeatable.')
    parser.add_argument('--set', action='append', default=[], metavar='KEY=VALUE',
                        help='Override a settings/main.lua value, e.g. --set RESTRICT_CONTENT=1 --set ENABLE_SOA=0. Repeatable.')
    parser.add_argument('--no-module-data', action='store_true',
                        help='Ignore modules/<entry>/zones/<zone>/mobs.yaml overlays listed in modules/init.txt.')
    parser.add_argument('--elements', choices=('rank', 'sdt'), default='rank',
                        help="How elemental modifiers are derived. 'rank' (default) turns each resistance rank into the "
                             "server's rank multiplier, on top of dmg_magic. 'sdt' uses dmg_magic alone, which most mobs leave unset.")
    parser.add_argument('--include-steal', action='store_true', help='List steal and despoil items alongside drops.')
    args = parser.parse_args()

    if args.build_names:
        names = build_client_names(args.build_names)
        if not names['zones']:
            sys.exit('No stock MobDB data files found in %s (generated files are ignored).' % args.build_names)
        with open(args.names, 'w', encoding='utf-8', newline='\n') as handle:
            json.dump(names, handle, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
        print('Wrote %d names across %d zones to %s' % (len(names['all']), len(names['zones']), args.names))
        return

    if not args.server or not args.out:
        parser.error('--server and --out are required')
    if not os.path.exists(args.names):
        sys.exit('%s is missing. Build it once with --build-names <stock MobDB data folder>.' % args.names)
    Generator(args).run()


if __name__ == '__main__':
    main()
